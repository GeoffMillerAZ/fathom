// writeTree writes files (repo-relative path -> content) under root.
func writeTree(t *testing.T, root string, files map[string]string) {
	t.Helper()
	for rel, content := range files {
		full := filepath.Join(root, rel)
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(full, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
}

// ingestService ingests root as service into the store at storePath.
func ingestService(t *testing.T, storePath, service, root string) {
	t.Helper()
	var out bytes.Buffer
	if code := run([]string{"ingest", "--service", service, "--path", root, "--store", storePath}, &out, &out); code != 0 {
		t.Fatalf("ingest %s failed (%d): %s", service, code, out.String())
	}
}

// migrationStatusJSON runs `refactor status --migration` with extra args and
// returns the decoded report.
func migrationStatusJSON(t *testing.T, dir, storePath, migration string, extra ...string) migrationStatusReport {
	t.Helper()
	args := append([]string{"refactor", "status", "--migration", migration, "--store", storePath, "--json"}, extra...)
	code, out, errOut := runInDir(t, dir, args)
	if code != 0 {
		t.Fatalf("refactor status --migration failed (%d)\nstdout=%s\nstderr=%s", code, out, errOut)
	}
	var rep migrationStatusReport
	if err := json.Unmarshal([]byte(out), &rep); err != nil {
		t.Fatalf("decode %q: %v", out, err)
	}
	return rep
}

func repoOf(t *testing.T, rep migrationStatusReport, name string) migrationRepoWire {
	t.Helper()
	for _, r := range rep.Repositories {
		if r.Repository == name {
			return r
		}
	}
	t.Fatalf("no repository %q in %+v", name, rep.Repositories)
	return migrationRepoWire{}
}

// TestRefactorStatusMigrationShowsBlockers is CX-11w: OldFunc is being
// replaced by NewFunc (declared in newpkg/). Seven files still name OldFunc:
// its own declaration and one caller are free, one caller is governed by an
// error rule (a layer rule forbids caller/ importing newpkg/), one by a warn
// rule, one is generated by its header, one by .gitattributes, and one is
// both generated and governed (the rule, which is citable, wins). Each
// remaining site names its blocker in text and JSON; a done site has none.
func TestRefactorStatusMigrationShowsBlockers(t *testing.T) {
	dir := t.TempDir()
	root := filepath.Join(dir, "svc-a")
	call := func(pkg string) string {
		return "package " + pkg + "\n\nimport \"svc-a/oldpkg\"\n\nfunc use() { oldpkg.OldFunc() }\n"
	}
	writeTree(t, root, map[string]string{
		"go.mod":            "module svc-a\n\ngo 1.21\n",
		"oldpkg/def.go":     "package oldpkg\n\nfunc OldFunc() {}\n",
		"newpkg/def.go":     "package newpkg\n\nfunc NewFunc() {}\n",
		"caller/user.go":    call("caller"),
		"free/ok.go":        call("free"),
		"warn/w.go":         call("warn"),
		"gen/x.pb.go":       "// Code generated by protoc-gen-go. DO NOT EDIT.\n\n" + call("gen"),
		"pb/both.pb.go":     "// Code generated by protoc-gen-go. DO NOT EDIT.\n\n" + call("pb"),
		"attrgen/a.go":      call("attrgen"),
		"newuser/n.go":      "package newuser\n\nimport \"svc-a/newpkg\"\n\nfunc use() { newpkg.NewFunc() }\n",
		".gitattributes":    "# generated by a tool the header does not name\nattrgen/*.go linguist-generated=true\n",
		".fathom/guard.cue": guardCueForBlockers,
	})
	storePath := filepath.Join(t.TempDir(), "fleet.sqlite")
	ingestService(t, storePath, "svc-a", root)

	rep := migrationStatusJSON(t, dir, storePath, "symbol OldFunc -> NewFunc")
	a := repoOf(t, rep, "svc-a")
	got := map[string]*migrationBlockerWire{}
	for _, s := range a.Remaining {
		got[s.File] = s.Blocker
	}
	want := map[string]migrationBlockerWire{
		"caller/user.go": {Reason: "governed", Rule: "caller-not-newpkg"},
		"warn/w.go":      {Reason: "governed", Rule: "warn-not-newpkg (warn)"},
		"gen/x.pb.go":    {Reason: "generated"},
		"attrgen/a.go":   {Reason: "generated"},
		"pb/both.pb.go":  {Reason: "governed", Rule: "pb-not-newpkg"},
	}
	for file, w := range want {
		if b := got[file]; b == nil || *b != w {
			t.Errorf("%s blocker = %v, want %+v", file, b, w)
		}
	}
	for _, free := range []string{"free/ok.go", "oldpkg/def.go"} {
		if b, ok := got[free]; !ok || b != nil {
			t.Errorf("%s = %v (present %v), want a remaining site with no blocker", free, b, ok)
		}
	}
	if len(a.Remaining) != 7 {
		t.Errorf("%d remaining sites, want 7: %+v", len(a.Remaining), a.Remaining)
	}
	if len(a.Done) != 2 || a.Done[0].File != "newpkg/def.go" || a.Done[1].File != "newuser/n.go" || a.Done[0].Blocker != nil || a.Done[1].Blocker != nil {
		t.Errorf("done = %+v, want newpkg/def.go and newuser/n.go, unblocked", a.Done)
	}

	// The text names the same blockers beside the sites.
	code, out, errOut := runInDir(t, dir, []string{"refactor", "status", "--migration", "symbol OldFunc -> NewFunc", "--store", storePath})
	if code != 0 {
		t.Fatalf("text run failed (%d): %s", code, errOut)
	}
	for _, line := range []string{
		"svc-a: 7 remaining (5 blocked), 2 done",
		"caller/user.go:5 — blocked: governed by rule caller-not-newpkg",
		"warn/w.go:5 — blocked: governed by rule warn-not-newpkg (warn)",
		"pb/both.pb.go:7 — blocked: governed by rule pb-not-newpkg",
		"gen/x.pb.go:7 — blocked: generated code",
		"attrgen/a.go:5 — blocked: generated code",
	} {
		if !strings.Contains(out, line) {
			t.Errorf("text lacks %q:\n%s", line, out)
		}
	}
	if strings.Contains(out, "free/ok.go:5 — blocked") {
		t.Errorf("the free site is reported blocked:\n%s", out)
	}
}

const guardCueForBlockers = `guards: []
layer_rules: [
	{id: "caller-not-newpkg", kind: "import_direction", sentence: "caller must not import newpkg", from: ["caller"], to: ["newpkg"]},
	{id: "warn-not-newpkg", kind: "import_direction", sentence: "warn should not import newpkg", severity: "warn", from: ["warn"], to: ["newpkg"]},
	{id: "pb-not-newpkg", kind: "import_direction", sentence: "pb must not import newpkg", from: ["pb"], to: ["newpkg"]},
]
`

// TestMigrationBlockerFacts pins the pieces the verb resolves: where a To
// lives, which rule forbids it (import_direction and boundary, an error rule
// before a warn one), and what .gitattributes marks generated.
func TestMigrationBlockerFacts(t *testing.T) {
	root := t.TempDir()
	writeTree(t, root, map[string]string{"go.mod": "module example.com/app\n\ngo 1.21\n"})

	imp := review.Migration{Kind: review.MigrationImport, From: "example.com/app/old", To: "example.com/app/internal/new"}
	got := migrationTargetDirs(imp, root, nil)
	if fmt.Sprint(got) != "[example.com/app/internal/new internal/new]" {
		t.Errorf("import target dirs = %v, want the path as written and relative to the module", got)
	}
	if got := migrationTargetDirs(review.Migration{Kind: review.MigrationRoute, From: "GET /a", To: "GET /b"}, root, nil); len(got) != 0 {
		t.Errorf("a route names no package, got %v", got)
	}

	rules := []guardspec.LayerRule{
		{ID: "b-boundary", Kind: guardspec.Boundary, Severity: guardspec.SeverityError, Allow: []string{"svc/api"}, Guarded: []string{"internal/new"}},
		{ID: "a-warn", Kind: guardspec.ImportDirection, Severity: guardspec.SeverityWarn, From: []string{"svc/**"}, To: []string{"internal/new"}},
		{ID: "c-dir", Kind: guardspec.ImportDirection, Severity: guardspec.SeverityError, From: []string{"svc/web"}, To: []string{"internal/**"}},
	}
	targets := []string{"internal/new"}
	for dir, want := range map[string]string{
		"svc/api":      "a-warn (warn)", // on the boundary's allow list: only the warn rule reaches it
		"svc/web":      "b-boundary",    // error rules by id, b-boundary before c-dir, and any error before the warn
		"other":        "b-boundary",    // off the boundary's allow list
		"internal/new": "",              // a package does not import itself
	} {
		if got := governingLayerRule(rules, dir, targets); got != want {
			t.Errorf("governingLayerRule(%q) = %q, want %q", dir, got, want)
		}
	}
	if got := governingLayerRule(rules[2:], "svc/web", targets); got != "c-dir" {
		t.Errorf("import_direction alone = %q, want c-dir", got)
	}
	if got := governingLayerRule(rules[2:], "svc/jobs", targets); got != "" {
		t.Errorf("a file outside every rule's from = %q, want none", got)
	}

	attrs := parseLinguistGenerated([]byte("*.pb.go linguist-generated\n/api/gen/** linguist-generated=true\nvendor/** -linguist-generated\ndocs/ linguist-generated\n# c linguist-generated\n[attr]macro linguist-generated\nkeep.pb.go linguist-generated=false\n"))
	for file, want := range map[string]bool{
		"a/b/x.pb.go":        true,  // a slash-free pattern matches the name at any depth
		"api/gen/deep/x.go":  true,  // an anchored pattern with **
		"other/api/gen/x.go": false, // ... only at the root
		"docs/readme.md":     false, // a directory pattern matches no file
		"keep.pb.go":         false, // a later line unsets it
		"vendor/x.pb.go":     false, // ... as does a later -attribute
		"main.go":            false,
	} {
		if got := linguistGenerated(attrs, file); got != want {
			t.Errorf("linguistGenerated(%q) = %v, want %v", file, got, want)
		}
	}
}
