package main

// certify_manifest.go — "fathom certify manifest" (TC-12): regenerates
// docs/certifications.md deterministically from the certifications layer
// (certify.Gaps' own target universe, every kind, no --kind filter): one
// table per kind, sorted exactly like certify.Gaps already sorts its
// targets (kind then id). No timestamp is embedded — renderCertifyManifest
// is a pure function of the report, so re-running it against an UNCHANGED
// store byte-for-byte reproduces the committed file, which is what makes
// --check meaningful (a hand edit, or a real drift, is the only way to
// make it differ).
import (
	"bytes"
	"context"
	"fmt"
	"io"
	"os"
	"sort"
	"strings"

	"github.com/geoffmilleraz/fathom/internal/certify"
	"github.com/geoffmilleraz/fathom/internal/store"
)

// certifyManifestHeader is the artifact's own "this is generated" marker
// (design doc §5's rendering, TC-12's own plan-row wording) — checked
// verbatim by TestCmdCertifyManifest_RegeneratedAndCheck so the contract
// (never hand-edit this file) cannot silently rot out of the generator.
const certifyManifestHeader = "<!-- generated by `fathom certify manifest` — do not edit by hand; regenerate with `fathom certify manifest --out docs/certifications.md` -->"

func cmdCertifyManifest(args []string, stdout, stderr io.Writer) int {
	fs := newFlagSet("certify manifest", stderr)
	service := fs.String("service", "", "service ID (default: resolved from the repo directory name)")
	storePath := fs.String("store", defaultStorePath(), "store path (.sqlite/.db)")
	out := fs.String("out", "docs/certifications.md", "path to write the generated artifact")
	check := fs.Bool("check", false, "exit 1 when the committed file differs from what would be generated, without writing")
	if err := fs.Parse(args); err != nil {
		return 1
	}

	svc := *service
	if svc == "" {
		svc = defaultTestsCoverageService()
		if svc == "" {
			fmt.Fprintln(stderr, "error: certify manifest requires --service (could not guess one from the current directory)")
			return 1
		}
	}

	st, err := store.Open(*storePath)
	if err != nil {
		fmt.Fprintf(stderr, "error: open store %q: %v\n", *storePath, err)
		return 1
	}
	defer st.Close()
	ctx := context.Background()

	corpusRoot := ""
	if meta, found, merr := st.GetServiceMeta(ctx, svc); merr == nil && found {
		corpusRoot = meta.Path
	}

	report, err := certify.Gaps(ctx, st, svc, corpusRoot, nil)
	if err != nil {
		fmt.Fprintf(stderr, "error: certify manifest for %q: %v\n", svc, err)
		return 1
	}
	generated := renderCertifyManifest(svc, report)

	if *check {
		committed, rerr := os.ReadFile(*out)
		if rerr != nil {
			fmt.Fprintf(stderr, "certify manifest --check: could not read %q: %v\n", *out, rerr)
			return 1
		}
		if !bytes.Equal(committed, []byte(generated)) {
			fmt.Fprintf(stderr, "certify manifest --check: %q is stale — regenerate with `fathom certify manifest --out %s`\n", *out, *out)
			return 1
		}
		fmt.Fprintf(stdout, "certify manifest --check: %q is current\n", *out)
		return 0
	}

	if err := os.WriteFile(*out, []byte(generated), 0o644); err != nil {
		fmt.Fprintf(stderr, "error: write %q: %v\n", *out, err)
		return 1
	}
	fmt.Fprintf(stdout, "certify manifest: wrote %q (%d target(s))\n", *out, len(report.Targets))
	return 0
}

// renderCertifyManifest is a pure function of (service, report): the same
// inputs always produce the same bytes (deterministic-output contract).
func renderCertifyManifest(service string, report certify.GapReport) string {
	var b strings.Builder
	b.WriteString(certifyManifestHeader)
	b.WriteString("\n\n# Certifications — ")
	b.WriteString(service)
	b.WriteString("\n\n")
	fmt.Fprintf(&b, "%d declared, %d live, %d gap(s), joined %d of %d cases.\n\n",
		report.Summary.Declared, report.Summary.Live, report.Summary.Gaps,
		report.Summary.JoinedCases, report.Summary.Cases)

	byKind := map[string][]certify.GapTarget{}
	var kinds []string
	for _, t := range report.Targets {
		if _, ok := byKind[t.Kind]; !ok {
			kinds = append(kinds, t.Kind)
		}
		byKind[t.Kind] = append(byKind[t.Kind], t)
	}
	sort.Strings(kinds)

	if len(kinds) == 0 {
		b.WriteString("No targets found: nothing declared, and no invariant/incident corpus read.\n")
		return b.String()
	}

	for _, kind := range kinds {
		fmt.Fprintf(&b, "## %s\n\n", kind)
		b.WriteString("| ID | Gap | Certificates | Remedy |\n")
		b.WriteString("|---|---|---|---|\n")
		for _, t := range byKind[kind] {
			gap := "no"
			if t.Gap {
				gap = "yes"
			}
			var certs []string
			for _, c := range t.Certificates {
				certs = append(certs, fmt.Sprintf("%s (%s, %s)", c.Test, c.Strength, c.State))
			}
			certCell := strings.Join(certs, "; ")
			if certCell == "" {
				certCell = "—"
			}
			remedy := t.Remedy
			if remedy == "" {
				remedy = "—"
			}
			fmt.Fprintf(&b, "| %s | %s | %s | %s |\n", t.ID, gap, certCell, remedy)
		}
		b.WriteString("\n")
	}
	return strings.TrimRight(b.String(), "\n") + "\n"
}
