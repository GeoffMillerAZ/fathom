// cmdGenPlanCue implements "gen-plan-cue": it parses a Markdown plan, emits a
// generated-only CUE document conforming to schema/plan #Plan (v2 fields
// included), and proves the emission is LOSSLESS by re-parsing it and
// comparing task-for-task with the Markdown parse (ADR-018 §3: CUE is the
// typed shadow, never the authoring surface).
//
// Exit codes: 0 emitted and round-trip verified; 2 operational error
// (unreadable plan, round-trip loss, unwritable output).
func cmdGenPlanCue(args []string, stdout, stderr io.Writer) int {
	fs := newFlagSet("gen-plan-cue", stderr)
	planPath := fs.String("plan", "", "Markdown plan file (required)")
	service := fs.String("service", "", "service ID (required)")
	output := fs.String("output", "", "output path (default: stdout)")
	if err := fs.Parse(args); err != nil {
		return 2
	}
	if *planPath == "" || *service == "" {
		fmt.Fprintln(stderr, "error: --plan and --service are required")
		fs.Usage()
		return 2
	}
	raw, err := os.ReadFile(*planPath)
	if err != nil {
		fmt.Fprintf(stderr, "error: reading plan: %v\n", err)
		return 2
	}
	plan := verify.ParseMarkdownPlan(*service, raw)
	for _, w := range verify.LintPlan(plan) {
		fmt.Fprintf(stderr, "lint: %s\n", w)
	}

	doc := renderPlanCUE(plan)

	// Round-trip: the emitted CUE must rebuild the identical Plan, less
	// what stripMarkdownPosition names.
	back, err := planFromCUE([]byte(doc))
	if err != nil {
		fmt.Fprintf(stderr, "error: round-trip parse of emitted CUE failed: %v\n", err)
		return 2
	}
	stripMarkdownPosition(&plan)
	if !reflect.DeepEqual(plan, back) {
		fmt.Fprintf(stderr, "error: round-trip loss — emitted CUE does not rebuild the parsed plan\n")
		for i := range plan.Tasks {
			if i >= len(back.Tasks) || !reflect.DeepEqual(plan.Tasks[i], back.Tasks[i]) {
				fmt.Fprintf(stderr, "  first divergence at task %d (%s)\n", i, plan.Tasks[i].ID)
				break
			}
		}
		return 2
	}

	if *output == "" {
		fmt.Fprint(stdout, doc)
		return 0
	}
	if err := os.WriteFile(*output, []byte(doc), 0o644); err != nil {
		fmt.Fprintf(stderr, "error: writing %s: %v\n", *output, err)
		return 2
	}
	fmt.Fprintf(stdout, "wrote %s (%d tasks, round-trip verified)\n", *output, len(plan.Tasks))
	return 0
}

// renderPlanCUE renders a verify.Plan as a deterministic, generated-only CUE
// document. Only set fields are emitted; absent fields decode to zero values,
// preserving Expect's strict-by-default semantics.
func renderPlanCUE(p verify.Plan) string {
	var b strings.Builder
	b.WriteString("// Code generated by fathom gen-plan-cue; DO NOT EDIT.\n")
	b.WriteString("// CUE is the typed shadow of the Markdown plan (ADR-018 §3).\n")
	b.WriteString("package plan\n\n")
	fmt.Fprintf(&b, "service: %q\n", p.Service)
	if p.Baseline != "" {
		fmt.Fprintf(&b, "baseline: %q\n", p.Baseline)
	}
	if p.Proof != "" {
		fmt.Fprintf(&b, "proof: %q\n", p.Proof)
	}
	b.WriteString("tasks: [\n")
	for _, t := range p.Tasks {
		b.WriteString("\t{\n")
		fmt.Fprintf(&b, "\t\tid: %q\n", t.ID)
		if t.Title != "" {
			fmt.Fprintf(&b, "\t\ttitle: %q\n", t.Title)
		}
		writeCUEList(&b, "\t\t", "spec_ids", t.SpecIDs)
		switch {
		case t.Claimed:
			b.WriteString("\t\tstate: \"claimed\"\n")
		case t.Skipped:
			b.WriteString("\t\tstate: \"skipped\"\n")
		case t.InProgress:
			b.WriteString("\t\tstate: \"in-progress\"\n")
		}
		if t.Disposition != "" {
			fmt.Fprintf(&b, "\t\tdisposition: %q\n", t.Disposition)
		}
		if t.Reason != "" {
			fmt.Fprintf(&b, "\t\treason: %q\n", t.Reason)
		}
		if t.Trigger != "" {
			fmt.Fprintf(&b, "\t\ttrigger: %q\n", t.Trigger)
		}
		if !t.Expect.IsZero() || t.Oracle != "" || t.Max != nil || t.Min != nil || t.Eq != nil {
			b.WriteString("\t\texpect: {\n")
			e := t.Expect
			if e.Symbol != "" {
				fmt.Fprintf(&b, "\t\t\tsymbol: %q\n", e.Symbol)
			}
			if e.Package != "" {
				fmt.Fprintf(&b, "\t\t\tpackage: %q\n", e.Package)
			}
			if e.ReachableFrom != "" {
				fmt.Fprintf(&b, "\t\t\treachable_from: %q\n", e.ReachableFrom)
			}
			if e.SkipTest {
				b.WriteString("\t\t\tskip_test: true\n")
			}
			if e.SkipReason != "" {
				fmt.Fprintf(&b, "\t\t\tskip_reason: %q\n", e.SkipReason)
			}
			if e.AllowContradiction {
				b.WriteString("\t\t\tallow_contradiction: true\n")
			}
			if e.MinTier != "" {
				fmt.Fprintf(&b, "\t\t\tmin_tier: %q\n", string(e.MinTier))
			}
			if e.Library {
				b.WriteString("\t\t\tlibrary: true\n")
			}
			// ADR-043: the certification keys sit beside the symbol
			// they certify.
			writeCUEList(&b, "\t\t\t", "certified_by", e.CertifiedBy)
			writeCUEString(&b, "\t\t\t", "strength", e.CertifyStrength)
			// ADR-030 and ADR-034 decision 2: the lexical and ledger
			// oracle keys live in #Expect beside the symbol contract they
			// are the alternative to.
			if t.Oracle != "" {
				fmt.Fprintf(&b, "\t\t\toracle: %q\n", t.Oracle)
				writeCUEString(&b, "\t\t\t", "path", t.OraclePath)
				writeCUEString(&b, "\t\t\t", "pattern", t.OraclePattern)
				writeCUEString(&b, "\t\t\t", "run_id", t.OracleRunID)
				writeCUEString(&b, "\t\t\t", "task", t.OracleTaskID)
				writeCUEString(&b, "\t\t\t", "arm", t.OracleArm)
				writeCUEString(&b, "\t\t\t", "min_trials", t.OracleMinTrials)
				writeCUEString(&b, "\t\t\t", "criterion", t.OracleCriterion)
				writeCUEString(&b, "\t\t\t", "accept_verdict", t.OracleAcceptVerdict)
			}
			// ADR-044 §3.1: a lexical oracle's match-count bounds.
			for _, bound := range []struct {
				key string
				v   *int
			}{{"max", t.Max}, {"min", t.Min}, {"eq", t.Eq}} {
				if bound.v != nil {
					fmt.Fprintf(&b, "\t\t\t%s: %d\n", bound.key, *bound.v)
				}
			}
			b.WriteString("\t\t}\n")
		}
		// WF-3 and the pack pointers: needs and ctx sit on #Task.
		writeCUEList(&b, "\t\t", "needs", t.Needs)
		writeCUEList(&b, "\t\t", "ctx", t.Ctx)
		// ADR-044: the refactor-conservation keys.
		writeCUEString(&b, "\t\t", "gone", t.Gone)
		writeCUEString(&b, "\t\t", "tests", t.Tests)
		writeCUEList(&b, "\t\t", "paths", t.GonePaths)
		writeCUEList(&b, "\t\t", "retires", t.Retires)
		writeCUEList(&b, "\t\t", "surface_change", t.SurfaceChange)
		// ADR-049 (SI-7/SI-8): weight (only when not the default 1) and
		// accept sit on #Task beside the contract, never inside it.
		if t.Weight > 1 {
			fmt.Fprintf(&b, "\t\tweight: %d\n", t.Weight)
		}
		if t.Accept != "" {
			fmt.Fprintf(&b, "\t\taccept: %q\n", t.Accept)
		}
		b.WriteString("\t},\n")
	}
	b.WriteString("]\n")
	return b.String()
}

// writeCUEString writes `key: "v"` at indent when v is set.
func writeCUEString(b *strings.Builder, indent, key, v string) {
	if v != "" {
		fmt.Fprintf(b, "%s%s: %q\n", indent, key, v)
	}
}

// writeCUEList writes `key: ["a", "b"]` at indent when xs is non-empty.
func writeCUEList(b *strings.Builder, indent, key string, xs []string) {
	if len(xs) == 0 {
		return
	}
	quoted := make([]string, len(xs))
	for i, s := range xs {
		quoted[i] = fmt.Sprintf("%q", s)
	}
	fmt.Fprintf(b, "%s%s: [%s]\n", indent, key, strings.Join(quoted, ", "))
}

// cuePlanExpect / cuePlanTask / cuePlanDoc are the decode targets for
// planFromCUE. Field names mirror schema/plan #Plan.
type cuePlanExpect struct {
	Symbol             string   `json:"symbol"`
	Package            string   `json:"package"`
	ReachableFrom      string   `json:"reachable_from"`
	SkipTest           bool     `json:"skip_test"`
	SkipReason         string   `json:"skip_reason"`
	AllowContradiction bool     `json:"allow_contradiction"`
	MinTier            string   `json:"min_tier"`
	Library            bool     `json:"library"`
	CertifiedBy        []string `json:"certified_by"`
	Strength           string   `json:"strength"`
	Oracle             string   `json:"oracle"`
	Path               string   `json:"path"`
	Pattern            string   `json:"pattern"`
	RunID              string   `json:"run_id"`
	Task               string   `json:"task"`
	Arm                string   `json:"arm"`
	MinTrials          string   `json:"min_trials"`
	Criterion          string   `json:"criterion"`
	AcceptVerdict      string   `json:"accept_verdict"`
	Max                *int     `json:"max"`
	Min                *int     `json:"min"`
	Eq                 *int     `json:"eq"`
}

type cuePlanTask struct {
	ID            string         `json:"id"`
	Title         string         `json:"title"`
	SpecIDs       []string       `json:"spec_ids"`
	State         string         `json:"state"`
	Disposition   string         `json:"disposition"`
	Reason        string         `json:"reason"`
	Trigger       string         `json:"trigger"`
	Expect        *cuePlanExpect `json:"expect"`
	Needs         []string       `json:"needs"`
	Ctx           []string       `json:"ctx"`
	Gone          string         `json:"gone"`
	Tests         string         `json:"tests"`
	Paths         []string       `json:"paths"`
	Retires       []string       `json:"retires"`
	SurfaceChange []string       `json:"surface_change"`
	Weight        int            `json:"weight"`
	Accept        string         `json:"accept"`
}

type cuePlanDoc struct {
	Service  string        `json:"service"`
	Baseline string        `json:"baseline"`
	Proof    string        `json:"proof"`
	Tasks    []cuePlanTask `json:"tasks"`
}

// planFromCUE compiles a generated plan-CUE document and rebuilds the
// verify.Plan it encodes — the read half of the round-trip proof.
func planFromCUE(src []byte) (verify.Plan, error) {
	v := cuecontext.New().CompileBytes(src)
	if err := v.Err(); err != nil {
		return verify.Plan{}, fmt.Errorf("compile: %w", err)
	}
	var doc cuePlanDoc
	if err := v.Decode(&doc); err != nil {
		return verify.Plan{}, fmt.Errorf("decode: %w", err)
	}
	plan := verify.Plan{Service: doc.Service, Baseline: doc.Baseline, Proof: doc.Proof}
	for _, ct := range doc.Tasks {
		t := verify.Task{
			ID:            ct.ID,
			Title:         ct.Title,
			SpecIDs:       ct.SpecIDs,
			Claimed:       ct.State == "claimed",
			Skipped:       ct.State == "skipped",
			InProgress:    ct.State == "in-progress",
			Disposition:   ct.Disposition,
			Reason:        ct.Reason,
			Trigger:       ct.Trigger,
			Needs:         ct.Needs,
			Ctx:           ct.Ctx,
			Gone:          ct.Gone,
			Tests:         ct.Tests,
			GonePaths:     ct.Paths,
			Retires:       ct.Retires,
			SurfaceChange: ct.SurfaceChange,
			Weight:        ct.Weight,
			Accept:        ct.Accept,
		}
		if t.Weight < 1 {
			t.Weight = 1 // absent: the grammar's default
		}
		if ct.Expect != nil {
			t.Expect = verify.Expect{
				Symbol:             ct.Expect.Symbol,
				Package:            ct.Expect.Package,
				ReachableFrom:      ct.Expect.ReachableFrom,
				SkipTest:           ct.Expect.SkipTest,
				SkipReason:         ct.Expect.SkipReason,
				AllowContradiction: ct.Expect.AllowContradiction,
				MinTier:            core.EvidenceTier(ct.Expect.MinTier),
				Library:            ct.Expect.Library,
				CertifiedBy:        ct.Expect.CertifiedBy,
				CertifyStrength:    ct.Expect.Strength,
			}
			t.Oracle = ct.Expect.Oracle
			t.OraclePath = ct.Expect.Path
			t.OraclePattern = ct.Expect.Pattern
			t.OracleRunID = ct.Expect.RunID
			t.OracleTaskID = ct.Expect.Task
			t.OracleArm = ct.Expect.Arm
			t.OracleMinTrials = ct.Expect.MinTrials
			t.OracleCriterion = ct.Expect.Criterion
			t.OracleAcceptVerdict = ct.Expect.AcceptVerdict
			t.Max, t.Min, t.Eq = ct.Expect.Max, ct.Expect.Min, ct.Expect.Eq
		}
		plan.Tasks = append(plan.Tasks, t)
	}
	return plan, nil
}

// stripMarkdownPosition zeroes what the CUE shadow does not carry: a row's
// Line and EndLine are its Markdown position (a SARIF location, never a
// contract), and UnreadAnnotation, AnnotationSuspect, CtxMalformed,
// BoundsInvalid and WeightInvalid are lint findings about malformed
// Markdown, printed before the round trip; the shadow carries the typed
// value the parser kept (weight 1, no bound, no ctx), never the malformed
// text, so no schema key exists for them. UnparsedRows is the plan-level
// one: lines read as no row, which the shadow cannot carry either.
func stripMarkdownPosition(plan *verify.Plan) {
	plan.UnparsedRows = nil
	for i := range plan.Tasks {
		t := &plan.Tasks[i]
		t.Line, t.EndLine = 0, 0
		t.UnreadAnnotation, t.AnnotationSuspect = "", ""
		t.CtxMalformed, t.BoundsInvalid, t.WeightInvalid = false, nil, ""
	}
}

// genPlanCueRunner runs `fathom gen-plan-cue` (registered below; EW-45).
type genPlanCueRunner struct{}

func (genPlanCueRunner) execVerb(args []string, _ io.Reader, stdout, stderr io.Writer) int {
	return cmdGenPlanCue(args, stdout, stderr)
}

func init() {
	// SR-30: internal dev/round-trip tooling (ADR-018 decision 3), not
	// agent-facing
	declareVerb(verb{Name: "gen-plan-cue", Group: "operate", Order: 60, Hidden: true, Run: genPlanCueRunner{},
		Summary: "Emit the generated CUE shadow of a Markdown plan (round-trip verified)"})
}
