package main

// edithook_stale_enforce_test.go — J2 (e): the enforcement path (ADR-038,
// internal/guardspec/enforce.go / cmd/fathom/enforce.go) must never deny on
// a stale compiled rule. It already cannot, structurally:
// EvaluateGuardEnforcement/EvaluateLayerRuleEnforcement take a Guard/
// LayerRule plus the proposed edit's own path/text — never a claim or a
// Status — and evaluateEnforcedFileAtProjDir runs BEFORE any daemon
// round-trip (edithook_pre.go's own doc comment: "before the advisory path
// below ever runs (and before any daemon round-trip)"). This test proves
// that ordering behaviorally: a guard governing the edited file denies (or
// doesn't) purely on the structural check, and the daemon — which would
// serve a stale rule for this exact file if ever asked — is never even
// called deciding that.

import (
	"bytes"
	"encoding/json"
	"fmt"
	"net/http"
	"path/filepath"
	"strings"
	"sync/atomic"
	"testing"
)

func TestEditHookPre_EnforcedDeny_NeverConsultsStaleObligations(t *testing.T) {
	t.Setenv("HOME", t.TempDir())
	dir := t.TempDir()
	writeGuardCue(t, dir, `guards: [{
		enforce: true
		forbidden_paths: ["cmd/fathom/ui/app.css"]
		note: "generated by task ui:css — never hand-edit"
	}]`)
	file := filepath.Join(dir, "cmd", "fathom", "ui", "app.css")

	// If the enforcement decision ever consulted the daemon, it would see
	// THIS stale rule for the exact file being denied — proving the deny
	// (or its absence) is unaffected requires the daemon to serve
	// something that would visibly change the outcome if read. It never
	// gets read at all: calls stays 0.
	srv, calls := countingServer(t, func(w http.ResponseWriter, r *http.Request) {
		w.Header().Set("Content-Type", "application/json")
		fmt.Fprint(w, `{"jsonrpc":"2.0","id":1,"result":{"content":[{"type":"text","text":`+
			`"{\"service\":\"repo\",\"file\":\"cmd/fathom/ui/app.css\",\"rules\":[{\"rule\":\"Old rule.\",\"src\":\"CLAUDE.md#L1-L1\",\"tier\":\"obligation\",\"layer\":\"obligations\",\"status\":\"stale\"}]}"`+
			`}]}}`)
	})
	defer srv.Close()

	hookInput := fmt.Sprintf(`{"tool_name":"Write","tool_input":{"file_path":%q,"content":"body { color: red }"},"cwd":%q}`, file, dir)
	hookStdin(t, hookInput)

	var out, errBuf bytes.Buffer
	code := runWithStdin([]string{"edit-hook", "--pre", "--url=" + srv.URL}, nil, &out, &errBuf)
	if code != 0 {
		t.Fatalf("exit = %d, stderr = %s", code, errBuf.String())
	}
	var got map[string]any
	if err := json.Unmarshal(out.Bytes(), &got); err != nil {
		t.Fatalf("output is not JSON: %s", out.String())
	}
	hso, _ := got["hookSpecificOutput"].(map[string]any)
	if hso["permissionDecision"] != "deny" {
		t.Fatalf("output = %s, want a deny purely from the structural forbidden_paths check", out.String())
	}
	reason, _ := hso["permissionDecisionReason"].(string)
	if !strings.Contains(reason, "forbidden_paths") {
		t.Errorf("permissionDecisionReason = %q, want it to name forbidden_paths (never the stale rule)", reason)
	}
	if strings.Contains(reason, "Old rule") || strings.Contains(reason, "stale") {
		t.Errorf("permissionDecisionReason must never mention a stale obligation: %q", reason)
	}
	if n := atomic.LoadInt32(calls); n != 0 {
		t.Errorf("daemon queried %d time(s) deciding a structural deny, want 0 — a stale rule can never be consulted", n)
	}
}
