package main

// brief.go — OB-7: `fathom brief` renders the observatory's impact model to
// a dated LOCAL markdown value brief. Sharing is a human verb (law 13):
// this verb writes a file and stops — a person decides where it goes. The
// pitch is the discipline: real numbers with denominators, version stamps,
// and an explicit not-measured section.

import (
	"fmt"
	"io"
	"os"
	"path/filepath"
	"strconv"
	"strings"
	"time"
)

func cmdBrief(args []string, stdout, stderr io.Writer) int {
	fs := newFlagSet("brief", stderr)
	url := fs.String("url", defaultFathomURL(), "fathom serve-http base URL")
	outDir := fs.String("out", "", "output directory (default ~/.fathom/briefs)")
	printOnly := fs.Bool("print", false, "print the brief to stdout instead of writing a file")
	if err := fs.Parse(args); err != nil {
		return 1
	}

	now := time.Now()
	m := buildObservatoryModel(*url, now)
	md := renderBriefMD(m)

	if *printOnly {
		fmt.Fprint(stdout, md)
		return 0
	}

	dir := *outDir
	if dir == "" {
		home, err := os.UserHomeDir()
		if err != nil {
			fmt.Fprintf(stderr, "error: cannot resolve home dir for the default output location: %v (use --out)\n", err)
			return 1
		}
		dir = filepath.Join(home, ".fathom", "briefs")
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		fmt.Fprintf(stderr, "error: %v\n", err)
		return 1
	}
	path := filepath.Join(dir, "brief-"+now.UTC().Format("2006-01-02")+".md")
	if err := os.WriteFile(path, []byte(md), 0o644); err != nil {
		fmt.Fprintf(stderr, "error: %v\n", err)
		return 1
	}
	fmt.Fprintf(stdout, "brief written: %s\nsharing is a human verb — nothing was sent anywhere.\n", path)
	return 0
}

// renderBriefMD is the pure rendering core (OB-7's test surface).
func renderBriefMD(m observatoryModel) string {
	imp := m.Impact
	var b strings.Builder
	fmt.Fprintf(&b, "# fathom value brief — %s\n\n", m.GeneratedAt)
	fmt.Fprintf(&b, "> Generated by fathom %s. Every figure below names its instrument and\n> denominator; anything not measured says so. No estimates, no projections.\n\n", m.FathomVersion)

	b.WriteString("## Fleet\n\n")
	if m.DegradedNote != "" {
		b.WriteString("- " + m.DegradedNote + "\n")
	} else {
		totalSymbols, totalCalls, agentCalls := 0, 0, 0
		wired := 0
		for _, s := range m.Services {
			totalSymbols += s.Symbols
			totalCalls += s.CallsTotal
			agentCalls += s.CallsAgent
			if s.WiringRemedy == "" {
				wired++
			}
		}
		fmt.Fprintf(&b, "- %d services indexed · %d symbols\n", len(m.Services), totalSymbols)
		fmt.Fprintf(&b, "- %d of %d services with no outstanding wiring remedy\n", wired, len(m.Services))
		fmt.Fprintf(&b, "- %d recorded tool calls in the current call log (%d via the agent surface)\n", totalCalls, agentCalls)
	}

	b.WriteString("\n## Q2 — What did fathom prevent?\n\n")
	fmt.Fprintf(&b, "- ledger sessions: %d", imp.LedgerSessions)
	if imp.DateRange != "" {
		fmt.Fprintf(&b, " (%s)", imp.DateRange)
	}
	b.WriteString("\n")
	if imp.VerifyCatchesTotal != nil {
		fmt.Fprintf(&b, "- verify catches: %d — %s\n", *imp.VerifyCatchesTotal, imp.VerifyCatchesNote)
	}
	if imp.DiscoveryTotal != nil {
		fmt.Fprintf(&b, "- discovery actions: %d — %s\n", *imp.DiscoveryTotal, imp.DiscoveryNote)
	}

	fmt.Fprintf(&b, "- obligations served (calls): %d — rules injected before edits\n", imp.ObligationCalls)

	b.WriteString("\n## Q1 — What did the agent not have to do? (law 12: savings exist only as an arm range)\n\n")
	fmt.Fprintf(&b, "- pilot state: %s — %s\n", imp.PilotState, imp.PilotDetail)
	fmt.Fprintf(&b, "- ON arm: %d sessions", imp.TokensOnSessions)
	if imp.TokensOnMedian != nil {
		fmt.Fprintf(&b, ", median tokens %s", strconv.Itoa(*imp.TokensOnMedian))
	}
	b.WriteString("\n")
	fmt.Fprintf(&b, "- OFF arm: %d sessions", imp.TokensOffSessions)
	if imp.TokensOffMedian != nil {
		fmt.Fprintf(&b, ", median tokens %s", strconv.Itoa(*imp.TokensOffMedian))
	}
	b.WriteString("\n")

	b.WriteString("\n## Q3 — Where does the agent still flounder?\n\n")
	fmt.Fprintf(&b, "- open observations across the fleet: %d (each a bug spec with a repro)\n", briefOpenObservations(m))
	b.WriteString("- per-tool miss rates live on /observatory/impact (query text never logged)\n")

	b.WriteString("\n## Q4 — Is the knowledge compounding?\n\n")
	if imp.FirstEditMedian != nil {
		fmt.Fprintf(&b, "- median warm-up: %d turns to first edit — %s\n", *imp.FirstEditMedian, imp.FirstEditNote)
	} else {
		fmt.Fprintf(&b, "- warm-up (turns to first edit): %s\n", imp.FirstEditNote)
	}

	b.WriteString("\n## Not measured (named, per law 3)\n\n")
	absent := 0
	if imp.LedgerNote != "" {
		b.WriteString("- " + imp.LedgerNote + "\n")
		absent++
	}
	if imp.VerifyCatchesTotal == nil {
		b.WriteString("- " + imp.VerifyCatchesNote + "\n")
		absent++
	}
	if imp.DiscoveryTotal == nil {
		b.WriteString("- " + imp.DiscoveryNote + "\n")
		absent++
	}
	if imp.TokensOnMedian == nil && imp.LedgerSessions > 0 {
		b.WriteString("- ON-arm token totals absent from the ledger\n")
		absent++
	}
	if absent == 0 {
		b.WriteString("- every instrument above reported\n")
	}
	b.WriteString("\n---\nnarrative story rows, when present, are a lens over mechanism-labeled\nevents and are deliberately NOT quoted as evidence here (law 14).\n")
	return b.String()
}

// briefOpenObservations mirrors fleetOpenObservations for the brief.
func briefOpenObservations(m observatoryModel) int {
	total := 0
	for _, s := range m.Services {
		if s.OpenObservations != nil {
			total += *s.OpenObservations
		}
	}
	return total
}
