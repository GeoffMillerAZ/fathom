// TestEditHookPre_FATHOM_ENFORCE_Off_DowngradesToAdvisory is the escape
// hatch (ADR-038 item 3): with FATHOM_ENFORCE=off, an otherwise-denying
// edit is never denied — it falls through to the ordinary advisory path
// (which, with no daemon wired in this test, degrades to silence — the
// only assertion that matters here is "not a deny").
func TestEditHookPre_FATHOM_ENFORCE_Off_DowngradesToAdvisory(t *testing.T) {
	t.Setenv("HOME", t.TempDir())
	t.Setenv("FATHOM_ENFORCE", "off")
	dir := t.TempDir()
	writeGuardCue(t, dir, `guards: [{
		enforce: true
		forbidden_paths: ["cmd/fathom/ui/app.css"]
		note: "generated"
	}]`)
	file := filepath.Join(dir, "cmd", "fathom", "ui", "app.css")

	srv, _ := countingServer(t, func(w http.ResponseWriter, r *http.Request) {
		w.Write([]byte(`{"service":"repo"}`))
	})
	defer srv.Close()

	hookInput := fmt.Sprintf(`{"tool_name":"Write","tool_input":{"file_path":%q,"content":"body{}"},"cwd":%q}`, file, dir)
	hookStdin(t, hookInput)

	var out, errBuf bytes.Buffer
	code := runWithStdin([]string{"edit-hook", "--pre", "--url=" + srv.URL}, nil, &out, &errBuf)
	if code != 0 {
		t.Fatalf("exit = %d, stderr = %s", code, errBuf.String())
	}
	if strings.Contains(out.String(), "permissionDecision") {
		t.Errorf("FATHOM_ENFORCE=off must never deny, got %s", out.String())
	}
}

