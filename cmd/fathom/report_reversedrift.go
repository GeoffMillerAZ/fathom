package main

import (
	"context"
	"fmt"
	"sort"
	"strings"

	"github.com/geoffmilleraz/fathom/internal/analysis/apisurface"
	"github.com/geoffmilleraz/fathom/internal/core"
	"github.com/geoffmilleraz/fathom/internal/filter"
	"github.com/geoffmilleraz/fathom/internal/store"
)

// reverseDriftLayer is the semantic layer whose claims define "governed"
// for the reverse-drift report (E6-1, docs/plans/new-use-cases.md Phase E
// §E6): spec-bindings claims are compiled from gated plan rows' {symbol,
// package} contracts (internal/semantic/layers/spec-bindings/layer.cue) and
// carry a Scope of package-glob(s) — LC-6 binds a PACKAGE, not one symbol —
// so coverage here is a file-path-glob match, the same mechanism
// internal/semantic/serve.go's ObligationsFor already uses to match a claim
// to a file.
const reverseDriftLayer = "spec-bindings"

// runReverseDriftReport is `fathom report --analyzer reverse-drift`'s store
// orchestration: the service's exported public API surface
// (internal/analysis/apisurface.Surface, already tested) MINUS the paths
// covered by any served spec-bindings claim (already-compiled evidence —
// this report only READS the ledger; unlike the authorship report it never
// compiles or persists anything) = the ungoverned public surface. Read-only
// and deterministic: a pure function of the store's current content, so
// re-running it against an unchanged index reproduces identical bytes.
func runReverseDriftReport(ctx context.Context, st store.Store, service string) (string, error) {
	obs, err := st.QueryObservations(ctx, service, "")
	if err != nil {
		return "", fmt.Errorf("query observations for %q: %w", service, err)
	}
	nodes := make([]core.SymbolNode, 0, len(obs))
	for _, o := range obs {
		nodes = append(nodes, o.ToSymbolNode())
	}
	surface := apisurface.Surface(nodes)

	claims, err := st.ClaimsForService(ctx, service, reverseDriftLayer)
	if err != nil {
		return "", fmt.Errorf("list %s claims for %q: %w", reverseDriftLayer, service, err)
	}
	var scopes []string
	served := 0
	for _, c := range claims {
		if !c.Status.Served() {
			continue // superseded/refuted claims no longer govern anything
		}
		served++
		scopes = append(scopes, c.Scope...)
	}
	matcher := filter.New(scopes)

	var ungoverned []core.SymbolNode
	for _, n := range surface {
		if !matcher.Match(n.FilePath) {
			ungoverned = append(ungoverned, n)
		}
	}
	return renderReverseDriftReport(service, surface, ungoverned, served), nil
}

// renderReverseDriftReport is a pure function: identical input always
// renders identical bytes. surface is apisurface.Surface's output (sorted by
// Package, Name); ungoverned is the subset with no spec-bindings coverage,
// a sub-sequence of surface in the same relative order. servedClaims is the
// count of spec-bindings claims that contributed to the coverage check
// (Status.Served() == true).
func renderReverseDriftReport(service string, surface, ungoverned []core.SymbolNode, servedClaims int) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# reverse-drift findings — %s\n\n", service)
	b.WriteString("Generated by `fathom report --analyzer reverse-drift`. Do not edit by hand — re-run the report to refresh.\n\n")
	b.WriteString("Public API surface (internal/analysis/apisurface) minus spec-bindings\n")
	b.WriteString("coverage (internal/semantic/layers/spec-bindings — gated plan rows'\n")
	b.WriteString("`{symbol, package}` contracts compiled to claims) = surface no plan or\n")
	b.WriteString("spec governs, per docs/plans/new-use-cases.md Phase E §E6.\n\n")

	governed := len(surface) - len(ungoverned)
	coverage := 100.0
	if len(surface) > 0 {
		coverage = 100 * float64(governed) / float64(len(surface))
	}

	b.WriteString("| metric | value |\n")
	b.WriteString("|---|---|\n")
	fmt.Fprintf(&b, "| public API surface (total) | %d |\n", len(surface))
	fmt.Fprintf(&b, "| spec-bindings claims (served) | %d |\n", servedClaims)
	fmt.Fprintf(&b, "| governed (covered by a spec-binding) | %d |\n", governed)
	fmt.Fprintf(&b, "| ungoverned (no spec-binding covers it) | %d |\n", len(ungoverned))
	fmt.Fprintf(&b, "| coverage | %.1f%% |\n", coverage)

	if len(ungoverned) == 0 {
		b.WriteString("\nNo ungoverned public surface.\n")
		return b.String()
	}

	sorted := append([]core.SymbolNode(nil), ungoverned...)
	sort.Slice(sorted, func(i, j int) bool {
		if sorted[i].FilePath != sorted[j].FilePath {
			return sorted[i].FilePath < sorted[j].FilePath
		}
		if sorted[i].Line != sorted[j].Line {
			return sorted[i].Line < sorted[j].Line
		}
		return sorted[i].Name < sorted[j].Name
	})
	b.WriteString("\n## Ungoverned public surface\n\n")
	for _, n := range sorted {
		fmt.Fprintf(&b, "- `%s:%d` (%s) %s\n", n.FilePath, n.Line, n.Kind, symbolLabel(n))
	}
	return b.String()
}

// symbolLabel renders a symbol's display name: "Package.Name" when Package
// is set (mirrors apisurface's own internal symbolKey), else bare Name.
func symbolLabel(n core.SymbolNode) string {
	if n.Package == "" {
		return n.Name
	}
	return n.Package + "." + n.Name
}
