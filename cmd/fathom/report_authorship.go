// authorshipStaleAge mirrors internal/query's defaultMaxAge (24h): a source
// whose most recent observation is older than this, relative to the
// service's own last-ingest watermark (never wall-clock time — see
// deriveAuthorshipAsOf), counts as stale for this report's join.
const authorshipStaleAge = 24 * time.Hour

// runAuthorshipReport is `fathom report --analyzer authorship`'s store
// orchestration (E2-3, docs/plans/new-use-cases.md Phase E §E2): it loads a
// service's commits and observations, runs E2-2's deterministic
// Co-Authored-By oracle over the commits, PERSISTS the resulting claims (the
// ledger — this is the only call site that populates it), and renders the
// join of authorship share × staleness × complexity as markdown.
//
// PutClaims is an upsert keyed by (service, claim_id) — content-addressed
// IDs make re-running this command idempotent, so it stays safe to call on
// every report (no separate "compile" step exists or is needed).
func runAuthorshipReport(ctx context.Context, st store.Store, service string) (string, error) {
	commits, err := st.ListCommits(ctx, service)
	if err != nil {
		return "", fmt.Errorf("list commits for %q: %w", service, err)
	}
	obs, err := st.QueryObservations(ctx, service, "")
	if err != nil {
		return "", fmt.Errorf("query observations for %q: %w", service, err)
	}

	watermark, asOf := deriveAuthorshipAsOf(ctx, st, service, obs)

	claims, links := authorship.CompileClaims(service, commits, watermark, asOf)
	if len(claims) > 0 {
		if err := st.PutClaims(ctx, claims, links); err != nil {
			return "", fmt.Errorf("persist authorship claims for %q: %w", service, err)
		}
	}

	return renderAuthorshipReport(service, commits, claims, obs, asOf), nil
}

// deriveAuthorshipAsOf resolves the "as of" instant staleness is measured
// against, and the watermark recorded on emitted claims — both derived
// entirely from already-stored state, never from time.Now(), so the report
// stays a pure function of the store's current content (byte-identical
// across repeated runs against an unchanged index, matching every other
// `fathom report` analyzer's contract). Prefers ServiceMeta.IndexedAt (set
// at ingest time); falls back to the latest observation IngestedAt when no
// ServiceMeta row exists (e.g. a hand-built test store that never called
// SetServiceMeta); returns the zero Time when neither is available, in
// which case staleness is reported as unknown rather than guessed.
func deriveAuthorshipAsOf(ctx context.Context, st store.Store, service string, obs []core.Observation) (watermark string, asOf time.Time) {
	if meta, found, err := st.GetServiceMeta(ctx, service); err == nil && found && meta.IndexedAt != 0 {
		return meta.IndexedCommit, time.Unix(0, meta.IndexedAt).UTC()
	}
	var latest time.Time
	for _, o := range obs {
		if o.IngestedAt.After(latest) {
			latest = o.IngestedAt
		}
	}
	return "", latest
}

// renderAuthorshipReport is a pure function: identical input always renders
// identical bytes (no clock reads, no map-order dependence — every
// aggregate below is either a plain count or built from a slice sorted by
// this function itself).
func renderAuthorshipReport(service string, commits []store.Commit, claims []core.SemanticClaim, obs []core.Observation, asOf time.Time) string {
	coAuthored := map[string]bool{}
	for _, c := range claims {
		coAuthored[c.Subject] = true
	}
	commitsTotal := len(commits)
	commitsCoAuthored := len(coAuthored)
	sharePct := 0.0
	if commitsTotal > 0 {
		sharePct = 100 * float64(commitsCoAuthored) / float64(commitsTotal)
	}

	staleSources, totalSources := authorshipStaleness(obs, asOf, authorshipStaleAge)

	nodes := make([]core.SymbolNode, 0, len(obs))
	for _, o := range obs {
		nodes = append(nodes, o.ToSymbolNode())
	}
	funcs := complexity.Report(nodes) // ascending by Complexity, ties by Name
	avgComplexity := 0.0
	maxComplexity := 0
	maxComplexitySymbol := ""
	if len(funcs) > 0 {
		sum := 0
		for _, f := range funcs {
			sum += f.Complexity
		}
		avgComplexity = float64(sum) / float64(len(funcs))
		top := funcs[len(funcs)-1]
		maxComplexity = top.Complexity
		maxComplexitySymbol = fmt.Sprintf("%s:%d %s", top.FilePath, top.Line, top.Name)
	}

	asOfStr := "unknown"
	if !asOf.IsZero() {
		asOfStr = asOf.Format(time.RFC3339)
	}

	var b strings.Builder
	fmt.Fprintf(&b, "# authorship report — %s\n\n", service)
	b.WriteString("Generated by `fathom report --analyzer authorship`. Do not edit by hand — re-run the report to refresh.\n\n")
	b.WriteString("Joins AI co-authorship share (E2-2's deterministic, Model-empty\n")
	b.WriteString("Co-Authored-By trailer oracle, ADR-018 lexical class) against index\n")
	b.WriteString("staleness and code complexity, per docs/plans/new-use-cases.md Phase E\n")
	b.WriteString("§E2. Kill criterion: if this join shows no usable signal across the\n")
	b.WriteString("fleet, keep the authorship ledger and retract the risk-correlation pitch.\n\n")

	b.WriteString("| metric | value |\n")
	b.WriteString("|---|---|\n")
	fmt.Fprintf(&b, "| commits (total) | %d |\n", commitsTotal)
	fmt.Fprintf(&b, "| commits co-authored (AI trailer) | %d |\n", commitsCoAuthored)
	fmt.Fprintf(&b, "| co-authored share | %.1f%% |\n", sharePct)
	fmt.Fprintf(&b, "| authorship claims emitted | %d |\n", len(claims))
	fmt.Fprintf(&b, "| sources (total) | %d |\n", totalSources)
	fmt.Fprintf(&b, "| sources stale (>%s since watermark) | %d |\n", authorshipStaleAge, staleSources)
	fmt.Fprintf(&b, "| avg cyclomatic complexity (func/method) | %.2f |\n", avgComplexity)
	if maxComplexitySymbol != "" {
		fmt.Fprintf(&b, "| max cyclomatic complexity | %d (`%s`) |\n", maxComplexity, maxComplexitySymbol)
	} else {
		b.WriteString("| max cyclomatic complexity | n/a |\n")
	}
	fmt.Fprintf(&b, "| watermark (commit) | %s |\n", orNA(watermarkOrUnknown(claims)))
	fmt.Fprintf(&b, "| watermark (as of) | %s |\n", orNA(asOfStr))

	return b.String()
}

// watermarkOrUnknown reads the commit watermark recorded on any claim (every
// claim in one report run carries the same CompiledAtWatermark) — "unknown"
// when there are no claims to read it from.
func watermarkOrUnknown(claims []core.SemanticClaim) string {
	if len(claims) == 0 {
		return "unknown"
	}
	return claims[0].CompiledAtWatermark
}

func orNA(s string) string {
	if s == "" {
		return "unknown"
	}
	return s
}

// authorshipStaleness dedupes obs by SourceRef (latest IngestedAt wins, the
// same rule internal/query's StalenessReport uses), then counts how many
// are more than maxAge older than asOf. When asOf is the zero Time there is
// nothing honest to compare against, so every source is reported fresh
// (0 stale) rather than guessed — totalSources is still accurate.
func authorshipStaleness(obs []core.Observation, asOf time.Time, maxAge time.Duration) (stale, total int) {
	latest := map[string]time.Time{}
	for _, o := range obs {
		if t, ok := latest[o.SourceRef]; !ok || o.IngestedAt.After(t) {
			latest[o.SourceRef] = o.IngestedAt
		}
	}
	total = len(latest)
	if asOf.IsZero() {
		return 0, total
	}
	refs := make([]string, 0, len(latest))
	for ref := range latest {
		refs = append(refs, ref)
	}
	sort.Strings(refs) // deterministic iteration, even though only the count is used
	for _, ref := range refs {
		if asOf.Sub(latest[ref]) > maxAge {
			stale++
		}
	}
	return stale, total
}
