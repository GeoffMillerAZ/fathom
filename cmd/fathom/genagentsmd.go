// agentsMDTemplate is the deterministic template for the generated
// AGENTS.md (ADR-059: the one instruction file; `gen-claude-md` is its
// deprecated alias through 0.9.x). Fields are drawn from the symbolSummary
// type.
// Note: backtick characters inside the template are written as {{.BT}} using a
// FuncMap entry so the template itself can be expressed as a raw-string literal.
const agentsMDTemplate = `# {{.Service}} — Fathom Knowledge Index

> Auto-generated by fathom gen-agents-md on {{.Timestamp}}.
> Re-run after re-ingesting to keep this file current.

## Overview

| Field | Value |
|-------|-------|
| Service | {{.Service}} |
| Total Symbols | {{.TotalSymbols}} |
| Generated | {{.Timestamp}} |

## Language / Kind Breakdown

| Kind | Count |
|------|-------|
{{- range .KindCounts}}
| {{.Kind}} | {{.Count}} |
{{- end}}

## Exported Symbols ({{.TotalSymbols}})

{{- range .Symbols}}
- **{{.Name}}** ({{.Kind}}){{if .FilePath}} — {{.FilePath}}{{end}}{{if .Signature}}
  {{.Signature}}{{end}}
{{- end}}

## Tool Usage Guidance

- Use fathom query --service {{.Service}} --concern CONCERN --keywords KW
  to find symbols relevant to a concern.
- Use fathom inspect --service {{.Service}} to list all stored symbols.
- Use fathom ingest --service {{.Service}} to refresh the knowledge store.
`

// kindCount is a Kind → Count pair for the breakdown table.
type kindCount struct {
	Kind  string
	Count int
}

// symbolSummary holds all data needed to render the AGENTS.md template.
type symbolSummary struct {
	Service      string
	Timestamp    string
	TotalSymbols int
	KindCounts   []kindCount
	Symbols      []client.SymbolNode
}

// genAgentsMdDefaultOutput is where gen-agents-md writes by default.
const genAgentsMdDefaultOutput = "workspace/artifacts/AGENTS.md"

// cmdGenAgentsMd implements the gen-agents-md subcommand (AG-19).
func cmdGenAgentsMd(args []string, stdout, stderr io.Writer) int {
	return genInstructionsFile("gen-agents-md", genAgentsMdDefaultOutput, args, stdout, stderr)
}

// cmdGenClaudeMd is gen-claude-md, gen-agents-md's deprecated alias through
// 0.9.x (law 4: nothing a script calls disappears in the release that
// renames it). It keeps its own default output, so a script reading
// workspace/artifacts/CLAUDE.md keeps working, and says what to switch to.
func cmdGenClaudeMd(args []string, stdout, stderr io.Writer) int {
	fmt.Fprintln(stderr, "deprecated: `fathom gen-claude-md` is `fathom gen-agents-md` (default output "+genAgentsMdDefaultOutput+", ADR-059); this alias is removed after 0.9.x")
	return genInstructionsFile("gen-claude-md", "workspace/artifacts/CLAUDE.md", args, stdout, stderr)
}

// genInstructionsFile renders the knowledge index for one service into an
// instruction file.
func genInstructionsFile(verb, defaultOutput string, args []string, stdout, stderr io.Writer) int {
	fs := newFlagSet(verb, stderr)
	service := fs.String("service", "", "service ID (required)")
	storePath := fs.String("store", defaultStorePath(), "store path (.sqlite/.db)")
	output := fs.String("output", defaultOutput, "output path for the generated instruction file")

	if err := fs.Parse(args); err != nil {
		return 1
	}

	if *service == "" {
		fmt.Fprintln(stderr, "error: --service is required")
		fs.Usage()
		return 1
	}

	c, err := client.NewConstantClient(client.ModeLocal, *storePath)
	if err != nil {
		fmt.Fprintf(stderr, "error: opening client: %v\n", err)
		return 1
	}
	defer c.Close()

	symbols, err := c.ListAllSymbols(context.Background(), *service)
	if err != nil {
		fmt.Fprintf(stderr, "error: listing symbols: %v\n", err)
		return 1
	}

	// Build kind → count map.
	kindMap := make(map[string]int)
	for _, sym := range symbols {
		kindMap[string(sym.Kind)]++
	}
	var counts []kindCount
	for k, v := range kindMap {
		counts = append(counts, kindCount{Kind: k, Count: v})
	}
	sort.Slice(counts, func(i, j int) bool {
		return counts[i].Kind < counts[j].Kind
	})

	// Sort symbols deterministically for reproducible output.
	sorted := make([]client.SymbolNode, len(symbols))
	copy(sorted, symbols)
	sort.Slice(sorted, func(i, j int) bool {
		if sorted[i].Kind != sorted[j].Kind {
			return string(sorted[i].Kind) < string(sorted[j].Kind)
		}
		return sorted[i].Name < sorted[j].Name
	})

	summary := symbolSummary{
		Service:      *service,
		Timestamp:    time.Now().UTC().Format(time.RFC3339),
		TotalSymbols: len(symbols),
		KindCounts:   counts,
		Symbols:      sorted,
	}

	// Ensure the parent directory exists.
	if err := os.MkdirAll(filepath.Dir(*output), 0o755); err != nil {
		fmt.Fprintf(stderr, "error: creating output directory: %v\n", err)
		return 1
	}

	f, err := os.Create(*output)
	if err != nil {
		fmt.Fprintf(stderr, "error: creating output file %q: %v\n", *output, err)
		return 1
	}
	defer f.Close()

	tmpl, err := template.New("agents-md").
		Funcs(template.FuncMap{
			"lower": strings.ToLower,
		}).
		Parse(agentsMDTemplate)
	if err != nil {
		fmt.Fprintf(stderr, "error: parsing template: %v\n", err)
		return 1
	}

	if err := tmpl.Execute(f, summary); err != nil {
		fmt.Fprintf(stderr, "error: rendering template: %v\n", err)
		return 1
	}

	fmt.Fprintf(stdout, "wrote %s (%d symbols)\n", *output, len(symbols))
	return 0
}

// genAgentsMdRunner runs `fathom gen-agents-md` (registered below; EW-45).
type genAgentsMdRunner struct{}

func (genAgentsMdRunner) execVerb(args []string, _ io.Reader, stdout, stderr io.Writer) int {
	return cmdGenAgentsMd(args, stdout, stderr)
}

// genClaudeMdRunner runs `fathom gen-claude-md` (registered below; EW-45).
type genClaudeMdRunner struct{}

func (genClaudeMdRunner) execVerb(args []string, _ io.Reader, stdout, stderr io.Writer) int {
	return cmdGenClaudeMd(args, stdout, stderr)
}

func init() {
	declareVerb(verb{Name: "gen-agents-md", Group: "index", Order: 40, Run: genAgentsMdRunner{},
		Summary: "Generate an AGENTS.md knowledge index from stored symbols"})
	// ADR-059: renamed to gen-agents-md; a deprecated alias through 0.9.x
	// that stays dispatched for scripts.
	declareVerb(verb{Name: "gen-claude-md", Group: "index", Order: 50, Hidden: true, Run: genClaudeMdRunner{},
		Summary: "Deprecated alias of gen-agents-md (through 0.9.x)"})
}
