// statusCUETemplate renders a CUE status document conforming to
// schema/plan/#Status, deterministic for a given plan, index and set of
// attested runs except for one clock-dependent field: a runtime_pass
// criterion's detail names its run's age against the wall clock (EW-72,
// docs/usage/gen-status-cue.md). String values are quoted with %q to
// safely escape special characters.
const statusCUETemplate = `// Code generated by fathom gen-status-cue — do not hand-edit.
// Source of truth: the plan file. Re-run gen-status-cue to refresh.
package status

status: {
	service: {{printf "%q" .Service}}
	summary: {
		total:   {{.Summary.Total}}
		pass:    {{.Summary.Pass}}
		fail:    {{.Summary.Fail}}
		unknown: {{.Summary.Unknown}}
	}
	tasks: [
		{{- range .Tasks}}
		{
			id:     {{printf "%q" .TaskID}}
			{{- if .Title}}
			title:  {{printf "%q" .Title}}
			{{- end}}
			status: {{printf "%q" .Status}}
			label:  {{printf "%q" .Label}}
			criteria: [
				{{- range .Criteria}}
				{
					name:   {{printf "%q" .Name}}
					status: {{printf "%q" .Status}}
					{{- if .Detail}}
					detail: {{printf "%q" .Detail}}
					{{- end}}
				},
				{{- end}}
			]
		},
		{{- end}}
	]
}
`

// wirePlan is the JSON/CUE-decodable wire form of a plan file.
type wirePlan struct {
	Service string     `json:"service" cue:"service"`
	Tasks   []wireTask `json:"tasks"   cue:"tasks"`
}

type wireTask struct {
	ID      string     `json:"id"       cue:"id"`
	Title   string     `json:"title"    cue:"title"`
	SpecIDs []string   `json:"spec_ids" cue:"spec_ids"`
	Expect  wireExpect `json:"expect"   cue:"expect"`
}

type wireExpect struct {
	Symbol             string `json:"symbol"              cue:"symbol"`
	Package            string `json:"package"             cue:"package"`
	ReachableFrom      string `json:"reachable_from"      cue:"reachable_from"`
	SkipTest           bool   `json:"skip_test"           cue:"skip_test"`
	AllowContradiction bool   `json:"allow_contradiction" cue:"allow_contradiction"`
	MinTier            string `json:"min_tier"            cue:"min_tier"`
}

// cmdGenStatusCue implements the gen-status-cue subcommand. It loads a plan
// file, evaluates each task against the live fathom index, and writes a
// deterministic CUE status document to --output.
func cmdGenStatusCue(args []string, stdout, stderr io.Writer) int {
	fs := newFlagSet("gen-status-cue", stderr)
	planPath := fs.String("plan", "", "path to plan file (.cue, .json, or .md checklist) (required)")
	service := fs.String("service", "", "service ID (required)")
	storePath := fs.String("store", defaultStorePath(), "store path (.sqlite/.db)")
	output := fs.String("output", "workspace/artifacts/STATUS.cue", "output path for STATUS.cue")
	concern := fs.String("concern", "", "optional concern for contradiction scoping")

	if err := fs.Parse(args); err != nil {
		return 1
	}

	if *planPath == "" {
		fmt.Fprintln(stderr, "error: --plan is required")
		fs.Usage()
		return 1
	}
	if *service == "" {
		fmt.Fprintln(stderr, "error: --service is required")
		fs.Usage()
		return 1
	}

	// 1. Load and parse the plan file.
	plan, err := loadPlan(*planPath, *service)
	if err != nil {
		fmt.Fprintf(stderr, "error: loading plan: %v\n", err)
		return 1
	}

	// 2. Open the client and gather evidence.
	c, err := client.NewConstantClient(client.ModeLocal, *storePath)
	if err != nil {
		fmt.Fprintf(stderr, "error: opening client: %v\n", err)
		return 1
	}
	defer c.Close()

	ctx := context.Background()

	nodes, err := c.ListAllSymbols(ctx, *service)
	if err != nil {
		fmt.Fprintf(stderr, "error: listing symbols: %v\n", err)
		return 1
	}
	graph := callgraph.Build(nodes)

	// Typed Go call edges (ADR-021 §3): additive on top of the syntax graph
	// — best-effort, a non-Go service or a store with no typed edges yet
	// simply contributes nothing.
	if typed, typedErr := c.TypedEdges(ctx, *service); typedErr == nil {
		callgraph.AddTypedEdges(graph, typed)
	}

	// Contradictions — best-effort; scoped by concern when provided.
	var contras []core.Contradiction
	if res, qErr := c.QuerySymbols(ctx, core.Query{
		ServiceID: *service,
		ConcernID: *concern,
		TopN:      500,
	}); qErr == nil {
		contras = res.Contradictions
	}

	// Spec matrix — only built when at least one task has spec IDs.
	var (
		matrix  sdd.Matrix
		haveMat bool
	)
	for _, t := range plan.Tasks {
		if len(t.SpecIDs) > 0 {
			matrix = buildCLISpecMatrix(ctx, c, *service, nodes)
			haveMat = true
			break
		}
	}

	ev := &cliEvidence{
		ctx:     ctx,
		c:       c,
		service: *service,
		graph:   graph,
		contras: contras,
		matrix:  matrix,
		haveMat: haveMat,
		files:   verify.DirFiles(verifyRepoRoot()),
		product: callgraph.ProductEntryReach(graph),
	}

	// 3. Evaluate the plan.
	report := verify.VerifyPlan(plan, ev)

	// 4. Render the CUE status document.
	if err := os.MkdirAll(filepath.Dir(*output), 0o755); err != nil {
		fmt.Fprintf(stderr, "error: creating output directory: %v\n", err)
		return 1
	}

	f, err := os.Create(*output)
	if err != nil {
		fmt.Fprintf(stderr, "error: creating output file %q: %v\n", *output, err)
		return 1
	}
	defer f.Close()

	tmpl, err := template.New("status-cue").Parse(statusCUETemplate)
	if err != nil {
		fmt.Fprintf(stderr, "error: parsing template: %v\n", err)
		return 1
	}

	if err := tmpl.Execute(f, report); err != nil {
		fmt.Fprintf(stderr, "error: rendering template: %v\n", err)
		return 1
	}

	fmt.Fprintf(stdout, "wrote %s: %d tasks, %d verified, %d failing, %d unknown\n",
		*output, report.Summary.Total, report.Summary.Pass, report.Summary.Fail, report.Summary.Unknown)
	return 0
}

// loadPlan reads and decodes a plan file (JSON or CUE), applies the --service
// override, and returns a verify.Plan.
func loadPlan(path, serviceOverride string) (verify.Plan, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return verify.Plan{}, fmt.Errorf("reading %q: %w", path, err)
	}

	// Markdown checklist plans (e.g. TRACKING.md) parse directly. The service
	// must come from --service, since a Markdown plan has no service field.
	if strings.HasSuffix(path, ".md") {
		if serviceOverride == "" {
			return verify.Plan{}, fmt.Errorf("a Markdown plan requires --service")
		}
		return verify.ParseMarkdownPlan(serviceOverride, raw), nil
	}

	var wire wirePlan
	switch {
	case strings.HasSuffix(path, ".json"):
		if err := json.Unmarshal(raw, &wire); err != nil {
			return verify.Plan{}, fmt.Errorf("parsing JSON plan: %w", err)
		}
	default:
		// Treat as CUE (covers .cue and any other extension).
		cueCtx := cuecontext.New()
		v := cueCtx.CompileBytes(raw, cue.Filename(filepath.Base(path)))
		if err := v.Err(); err != nil {
			return verify.Plan{}, fmt.Errorf("parsing CUE plan: %w", err)
		}

		// Decode the top-level "plan" field if present; otherwise decode the
		// whole value (for inline plan-as-root files).
		target := v.LookupPath(cue.ParsePath("plan"))
		if !target.Exists() {
			target = v
		}
		if err := target.Decode(&wire); err != nil {
			return verify.Plan{}, fmt.Errorf("decoding CUE plan: %w", err)
		}
	}

	// --service wins over the plan's own service field.
	svc := wire.Service
	if serviceOverride != "" {
		svc = serviceOverride
	}

	plan := verify.Plan{Service: svc}
	for _, wt := range wire.Tasks {
		var mt core.EvidenceTier
		if core.EvidenceTier(wt.Expect.MinTier).Valid() {
			mt = core.EvidenceTier(wt.Expect.MinTier)
		}
		plan.Tasks = append(plan.Tasks, verify.Task{
			ID:      wt.ID,
			Title:   wt.Title,
			SpecIDs: wt.SpecIDs,
			Expect: verify.Expect{
				Symbol:             wt.Expect.Symbol,
				Package:            wt.Expect.Package,
				ReachableFrom:      wt.Expect.ReachableFrom,
				SkipTest:           wt.Expect.SkipTest,
				AllowContradiction: wt.Expect.AllowContradiction,
				MinTier:            mt,
			},
		})
	}
	return plan, nil
}

// buildCLISpecMatrix builds an sdd coverage matrix from a service's symbols
// and source files — mirrors buildSpecMatrix in internal/mcp/verify_plan_tool.go.
func buildCLISpecMatrix(ctx context.Context, c *client.Client, service string, nodes []core.SymbolNode) sdd.Matrix {
	codeRefs := map[string][]string{}
	for _, n := range nodes {
		if refs := sdd.ExtractRefs(n.Signature + " " + n.Name); len(refs) > 0 {
			codeRefs[n.Name] = refs
		}
	}
	if files, err := c.Sources(ctx, service); err == nil {
		for _, f := range files {
			if refs := sdd.ExtractRefs(string(f.Content)); len(refs) > 0 {
				codeRefs[f.Path] = append(codeRefs[f.Path], refs...)
			}
		}
	}
	// BuildMatrix requires a specs slice; pass nil — the matrix still
	// handles per-spec coverage lookups correctly.
	return sdd.BuildMatrix(nil, codeRefs)
}

// cliEvidence adapts the client + call graph to the verify.Evidence interface,
// mirroring verifyEvidence in internal/mcp/verify_plan_tool.go.
type cliEvidence struct {
	ctx     context.Context
	c       *client.Client
	service string
	graph   *callgraph.Graph
	contras []core.Contradiction
	matrix  sdd.Matrix
	haveMat bool
	// files is the working tree the lexical oracle (ADR-030) reads — the
	// same tree the plan file came from (verifyRepoRoot).
	files verify.FileEvidence
	// root is the same tree files reads, resolved once (verifyRepoRoot) —
	// verify_gone_evidence.go's git-aware precondition checks (IndexAtHead)
	// need the actual working-tree root, not just a ReadRepoFile closure.
	root string
	// byKey resolves a callgraph canonical key back to its defining
	// SymbolNode (file/line), for TypedCallers (verify_gone_evidence.go) —
	// the same map cmd/fathom/refactor_plan.go's buildRefactorPlan builds
	// from the identical nodes slice.
	byKey map[string]core.SymbolNode
	// product is what the service's product entry points reach, walked
	// once over graph (verify's `wired` criterion, ADR-018 amendment
	// 2026-09-28): one store, one watermark, one walk per process.
	product *callgraph.ProductReach
	// runtime is the service's attested runs (runtime_pass, TC-29), read
	// once on first use; runtimeErr names a failed read.
	runtime     *testevidence.RuntimeRuns
	runtimeErr  error
	runtimeRead bool
	// gone is the shared gone: evidence (internal/verify/goneev), built on
	// the first gone: row (verify_gone_evidence.go).
	gone *goneev.Evidence
}

// NewestAttestedRuns implements verify.RuntimeEvidence (TC-29): the
// newest attested run of each named test, read from the store's test_runs
// once per process — verify never runs a test.
func (e *cliEvidence) NewestAttestedRuns(tests []string) (map[string]verify.AttestedRun, error) {
	if !e.runtimeRead {
		e.runtimeRead = true
		e.runtime, e.runtimeErr = testevidence.LoadRuntimeRuns(e.ctx, e.c.Store(), e.service, nowFunc)
	}
	if e.runtimeErr != nil {
		return nil, e.runtimeErr
	}
	return e.runtime.NewestAttestedRuns(tests)
}

// Now implements verify.RuntimeEvidence: the injected wall clock.
func (e *cliEvidence) Now() time.Time { return nowFunc() }

// ReadRepoFile implements verify.FileEvidence over the repo's working tree.
func (e *cliEvidence) ReadRepoFile(path string) ([]byte, error) {
	if e.files == nil {
		return nil, fmt.Errorf("no repo root resolved for lexical oracles")
	}
	return e.files.ReadRepoFile(path)
}

// verifyRepoRoot is the root lexical-oracle paths resolve under: the git
// toplevel of the cwd (plans are read cwd-relative, so this is the tree
// the plan itself came from), else the cwd. The WORKING tree, never
// `git show HEAD:` — a plan and its evidence are read at the same moment.
func verifyRepoRoot() string {
	cwd, err := os.Getwd()
	if err != nil {
		return "."
	}
	if top := gitToplevel(cwd); top != "" {
		return top
	}
	return cwd
}

func (e *cliEvidence) FindSymbol(name string) []core.SymbolNode {
	nodes, err := e.c.FindSymbol(e.ctx, e.service, name)
	if err != nil {
		return nil
	}
	return nodes
}

func (e *cliEvidence) TestReaches(symbol string) []string {
	return callgraph.TestImpact(e.graph, symbol)
}

// TestReachesDetail implements verify.DetailedEvidence (ADR-021 §3): a path
// crossing a typed EdgeIfaceDispatch edge is surfaced distinctly in the
// verdict detail rather than reading identically to a direct static reach.
func (e *cliEvidence) TestReachesDetail(symbol string) []verify.ReachDetail {
	details := callgraph.TestImpactDetail(e.graph, symbol)
	out := make([]verify.ReachDetail, len(details))
	for i, d := range details {
		out[i] = verify.ReachDetail{Key: d.Key, ViaDispatch: d.ViaDispatch, Implementers: d.Implementers}
	}
	return out
}

// Reachable implements verify.Evidence over typed edges only (RF-5, I57):
// the same callgraph.ReachableTyped internal/mcp's verifyEvidence reads.
func (e *cliEvidence) Reachable(from, to string) bool {
	ok, _ := callgraph.ReachableTyped(e.graph, from, to)
	return ok
}

// ResolveReachName implements verify.ReachNameEvidence over the same graph
// Reachable walks.
func (e *cliEvidence) ResolveReachName(name string) (string, []string) {
	return callgraph.ReachName(e.graph, name)
}

// HeuristicReach implements verify.HeuristicReachEvidence: the heuristic
// edge a refused reach rested on.
func (e *cliEvidence) HeuristicReach(from, to string) (verify.HeuristicEdge, bool) {
	_, via := callgraph.ReachableTyped(e.graph, from, to)
	if via == nil {
		return verify.HeuristicEdge{}, false
	}
	return heuristicEdgeOf(*via), true
}

// heuristicEdgeOf translates callgraph's heuristic edge into verify's
// (verify imports no analysis package).
func heuristicEdgeOf(h callgraph.HeuristicEdge) verify.HeuristicEdge {
	return verify.HeuristicEdge{From: h.From, To: h.To, Kind: string(h.Kind), Tier: h.Tier().String()}
}

// ProductHeuristicReach implements verify.HeuristicReachEvidence: the
// product entry point that reaches symbol only through a heuristic edge.
func (e *cliEvidence) ProductHeuristicReach(symbol string) (string, verify.HeuristicEdge, bool) {
	if e.product == nil {
		e.product = callgraph.ProductEntryReach(e.graph)
	}
	entry, via, ok := e.product.HeuristicReachedBy(symbol)
	if !ok {
		return "", verify.HeuristicEdge{}, false
	}
	return entry, heuristicEdgeOf(via), true
}

// ProductEntryCount implements verify.ProductEvidence.
func (e *cliEvidence) ProductEntryCount() int {
	if e.product == nil {
		e.product = callgraph.ProductEntryReach(e.graph)
	}
	return len(e.product.Entries())
}

// ProductReachedBy implements verify.ProductEvidence.
func (e *cliEvidence) ProductReachedBy(symbol string) (string, bool) {
	if e.product == nil {
		e.product = callgraph.ProductEntryReach(e.graph)
	}
	return e.product.ReachedBy(symbol)
}

func (e *cliEvidence) Contradictions() []core.Contradiction { return e.contras }

func (e *cliEvidence) SpecImplementors(specID string) []string {
	if !e.haveMat {
		return nil
	}
	return e.matrix.Coverage(specID)
}

// CertificationsByTest implements verify.CertificationEvidence (vision 33
// / ADR-043 stage 1, TC-9): reads every compiled certifications-layer
// claim for the service and groups it by its provenance test's bare name
// via certify.ByTest — the SAME resolution internal/mcp's verifyEvidence
// uses, so `fathom verify` and verify_plan resolve a certified_by
// contract identically.
func (e *cliEvidence) CertificationsByTest(tests []string) map[string][]verify.Certification {
	claims, err := e.c.ClaimsForService(e.ctx, e.service, certify.Layer)
	if err != nil {
		return nil
	}
	return certify.ByTest(claims, tests)
}

