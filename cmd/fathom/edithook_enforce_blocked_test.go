package main

// edithook_enforce_blocked_test.go — PR-10 (docs/plans/served-not-kept.md):
// the PreToolUse enforce deny is the ONE place a `blocked` outcome exists,
// and until now nothing wrote it (ruleOutcomeBlocked was declared and never
// used). These tests drive cmdEditHookPre itself, with the real Claude
// codec, against an enforce:true guard.cue, and read the rule-outcome ledger
// (FATHOM_RULE_OUTCOME_LOG) the way GL-11's reader does.

import (
	"bufio"
	"bytes"
	"encoding/json"
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"testing"

	"github.com/geoffmilleraz/fathom/internal/harness"
)

// claimIDShape is core.ClaimID's own output shape: a lowercase sha256 hex.
// A blocked row's key must never match it (see enforceOutcomeID).
var claimIDShape = regexp.MustCompile(`^[0-9a-f]{64}$`)

// readOutcomeRows reads every row of the ledger at path; a log that was
// never created reads as zero rows (a deny that wrote nothing and a
// non-deny are the same observation here).
func readOutcomeRows(t *testing.T, path string) []ruleOutcomeEvent {
	t.Helper()
	f, err := os.Open(path)
	if os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		t.Fatal(err)
	}
	defer f.Close()
	var rows []ruleOutcomeEvent
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		var e ruleOutcomeEvent
		if err := json.Unmarshal(sc.Bytes(), &e); err != nil {
			t.Fatalf("ledger row is not JSON: %q: %v", sc.Text(), err)
		}
		rows = append(rows, e)
	}
	return rows
}

func blockedRows(rows []ruleOutcomeEvent) []ruleOutcomeEvent {
	var out []ruleOutcomeEvent
	for _, r := range rows {
		if r.Event == ruleOutcomeBlocked {
			out = append(out, r)
		}
	}
	return out
}

// enforceFixture is a fixture repo whose guard.cue carries one enforce:true
// file guard (forbidden_paths) and one enforce:true command guard, and an
// isolated rule-outcome ledger.
type enforceFixture struct {
	dir     string
	logPath string
}

func newEnforceFixture(t *testing.T) enforceFixture {
	t.Helper()
	t.Setenv("HOME", t.TempDir())
	logPath := filepath.Join(t.TempDir(), "rule-outcomes.jsonl")
	t.Setenv("FATHOM_RULE_OUTCOME_LOG", logPath)
	dir := t.TempDir()
	writeGuardCue(t, dir, `guards: [{
		enforce: true
		forbidden_paths: ["cmd/fathom/ui/app.css"]
		note: "generated by task ui:css — never hand-edit"
	}, {
		enforce: true
		command_scopes: ["cp * *libexec/fathom/fathom*"]
		note: "task deploy signs and asserts HEAD; a raw cp truncates a running binary (O25)"
	}]`)
	return enforceFixture{dir: dir, logPath: logPath}
}

func (f enforceFixture) fileEdit(rel string) harness.HookInput {
	return harness.HookInput{
		Event:     harness.EventPreTool,
		SessionID: "sess-pr10",
		Cwd:       f.dir,
		ToolName:  "Write",
		Tool:      harness.ToolFileEdit,
		FilePath:  filepath.Join(f.dir, filepath.FromSlash(rel)),
		// The deny is decided on the path alone (forbidden_paths), so the
		// content is immaterial.
		NewContent: "body { color: red }",
	}
}

func (f enforceFixture) shell(command string) harness.HookInput {
	return harness.HookInput{
		Event:     harness.EventPreTool,
		SessionID: "sess-pr10",
		Cwd:       f.dir,
		ToolName:  "Bash",
		Tool:      harness.ToolShell,
		Command:   command,
	}
}

// TestEnforceDenyWritesBlockedOutcome is PR-10's contract: an enforce deny
// that the codec actually emitted writes exactly one `blocked` row carrying
// the rule's id, the session and the file; an edit that is not denied writes
// none; and a deny the codec cannot render (it fell back to the advisory
// path) writes none, because nothing was blocked.
func TestEnforceDenyWritesBlockedOutcome(t *testing.T) {
	// The daemon must never be reached on an enforced deny, and on the
	// fall-through cases it answers nothing useful.
	unreachable := "http://127.0.0.1:1"

	t.Run("file deny writes one blocked row", func(t *testing.T) {
		f := newEnforceFixture(t)
		var out bytes.Buffer
		if code := cmdEditHookPre(harness.ClaudeCodec(), f.fileEdit("cmd/fathom/ui/app.css"), unreachable, false, &out); code != 0 {
			t.Fatalf("exit = %d", code)
		}
		if !strings.Contains(out.String(), `"permissionDecision":"deny"`) {
			t.Fatalf("output = %s, want a deny", out.String())
		}
		rows := blockedRows(readOutcomeRows(t, f.logPath))
		if len(rows) != 1 {
			t.Fatalf("blocked rows = %d (%+v), want exactly 1", len(rows), rows)
		}
		r := rows[0]
		if r.Session != "sess-pr10" {
			t.Errorf("session = %q, want sess-pr10", r.Session)
		}
		if r.File != "cmd/fathom/ui/app.css" {
			t.Errorf("file = %q, want the repo-relative path (the key served/violated rows use)", r.File)
		}
		if !strings.Contains(r.RuleID, "generated by task ui:css") {
			t.Errorf("rule_id = %q, want the violated guard's own id (its note)", r.RuleID)
		}
		if claimIDShape.MatchString(r.RuleID) {
			t.Errorf("rule_id %q is claim-shaped: a blocked row must never be able to collide with a claim id", r.RuleID)
		}
		if !strings.HasPrefix(r.RuleID, "enforce:") {
			t.Errorf("rule_id = %q, want the enforce: qualifier that keeps it apart from claim ids", r.RuleID)
		}
	})

	t.Run("command deny writes one blocked row with no file", func(t *testing.T) {
		f := newEnforceFixture(t)
		var out bytes.Buffer
		if code := cmdEditHookPre(harness.ClaudeCodec(), f.shell("cp -f bin/fathom /Users/x/.local/libexec/fathom/fathom"), unreachable, false, &out); code != 0 {
			t.Fatalf("exit = %d", code)
		}
		if !strings.Contains(out.String(), `"permissionDecision":"deny"`) {
			t.Fatalf("output = %s, want a deny", out.String())
		}
		rows := blockedRows(readOutcomeRows(t, f.logPath))
		if len(rows) != 1 {
			t.Fatalf("blocked rows = %d (%+v), want exactly 1", len(rows), rows)
		}
		r := rows[0]
		if r.Session != "sess-pr10" || r.File != "" {
			t.Errorf("row = %+v, want session sess-pr10 and no file (a command has none)", r)
		}
		if !strings.Contains(r.RuleID, "O25") || !strings.HasPrefix(r.RuleID, "enforce:") {
			t.Errorf("rule_id = %q, want the command guard's own id, enforce:-qualified", r.RuleID)
		}
	})

	t.Run("an edit that is not denied writes no blocked row", func(t *testing.T) {
		f := newEnforceFixture(t)
		var out bytes.Buffer
		if code := cmdEditHookPre(harness.ClaudeCodec(), f.fileEdit("cmd/fathom/main.go"), unreachable, false, &out); code != 0 {
			t.Fatalf("exit = %d", code)
		}
		if strings.Contains(out.String(), "permissionDecision") {
			t.Fatalf("output = %s, want no deny", out.String())
		}
		if rows := readOutcomeRows(t, f.logPath); len(rows) != 0 {
			t.Errorf("ledger rows = %+v, want none for an edit no rule denied", rows)
		}
		out.Reset()
		if code := cmdEditHookPre(harness.ClaudeCodec(), f.shell("echo hi"), unreachable, false, &out); code != 0 {
			t.Fatalf("exit = %d", code)
		}
		if rows := readOutcomeRows(t, f.logPath); len(rows) != 0 {
			t.Errorf("ledger rows = %+v, want none for a command no rule denied", rows)
		}
	})

	t.Run("enforcement off denies nothing and writes nothing", func(t *testing.T) {
		f := newEnforceFixture(t)
		t.Setenv("FATHOM_ENFORCE", "off")
		var out bytes.Buffer
		if code := cmdEditHookPre(harness.ClaudeCodec(), f.fileEdit("cmd/fathom/ui/app.css"), unreachable, false, &out); code != 0 {
			t.Fatalf("exit = %d", code)
		}
		if rows := readOutcomeRows(t, f.logPath); len(rows) != 0 {
			t.Errorf("ledger rows = %+v, want none: FATHOM_ENFORCE=off turned the rule advisory, nothing was blocked", rows)
		}
	})

	t.Run("a codec that cannot deny blocks nothing and writes nothing", func(t *testing.T) {
		f := newEnforceFixture(t)
		in := f.fileEdit("cmd/fathom/ui/app.css")
		var out bytes.Buffer
		if code := cmdEditHookPre(harness.GeminiCodec(), in, unreachable, false, &out); code != 0 {
			t.Fatalf("exit = %d", code)
		}
		if strings.Contains(out.String(), "deny") {
			t.Fatalf("output = %s: Gemini cannot deny", out.String())
		}
		if rows := readOutcomeRows(t, f.logPath); len(rows) != 0 {
			t.Errorf("ledger rows = %+v, want none: the deny was never emitted, so nothing was blocked", rows)
		}
		out.Reset()
		if code := cmdEditHookPre(harness.GeminiCodec(), f.shell("cp -f bin/fathom /Users/x/.local/libexec/fathom/fathom"), unreachable, false, &out); code != 0 {
			t.Fatalf("exit = %d", code)
		}
		if rows := readOutcomeRows(t, f.logPath); len(rows) != 0 {
			t.Errorf("ledger rows = %+v, want none for an un-emittable command deny", rows)
		}
	})

	t.Run("an unwritable ledger never breaks the deny", func(t *testing.T) {
		f := newEnforceFixture(t)
		// A log path whose parent is a regular file: MkdirAll fails.
		blocker := filepath.Join(t.TempDir(), "not-a-dir")
		if err := os.WriteFile(blocker, []byte("x"), 0o644); err != nil {
			t.Fatal(err)
		}
		t.Setenv("FATHOM_RULE_OUTCOME_LOG", filepath.Join(blocker, "rule-outcomes.jsonl"))
		var out bytes.Buffer
		if code := cmdEditHookPre(harness.ClaudeCodec(), f.fileEdit("cmd/fathom/ui/app.css"), unreachable, false, &out); code != 0 {
			t.Fatalf("exit = %d, want 0: the ledger failure must stay silent", code)
		}
		if !strings.Contains(out.String(), `"permissionDecision":"deny"`) {
			t.Errorf("output = %s, want the deny intact when the ledger cannot be written", out.String())
		}
	})
}

// TestRecordBlockedOutcomeRefusesAClaimShapedKey pins the collision
// guarantee at the writer: only an enforce:-qualified key is ever recorded,
// so a claim id (or any unqualified id) can never gain a blocked row through
// this path.
func TestRecordBlockedOutcomeRefusesAClaimShapedKey(t *testing.T) {
	logPath := filepath.Join(t.TempDir(), "rule-outcomes.jsonl")
	t.Setenv("FATHOM_RULE_OUTCOME_LOG", logPath)

	claim := strings.Repeat("ab", 32)
	if !claimIDShape.MatchString(claim) {
		t.Fatal("fixture is not claim-shaped")
	}
	recordBlockedOutcome(claim, "s", "f.go")
	recordBlockedOutcome("I19", "s", "f.go")
	recordBlockedOutcome("", "s", "f.go")
	if rows := readOutcomeRows(t, logPath); len(rows) != 0 {
		t.Fatalf("rows = %+v, want none for unqualified or blank keys", rows)
	}

	recordBlockedOutcome(enforceOutcomeID("org_token", "I19"), "s", "f.go")
	rows := readOutcomeRows(t, logPath)
	if len(rows) != 1 || rows[0].RuleID != "enforce:org_token:I19" || rows[0].Event != ruleOutcomeBlocked {
		t.Fatalf("rows = %+v, want one blocked row keyed enforce:org_token:I19", rows)
	}
	if got := enforceOutcomeID("forbidden_path", ""); got != "" {
		t.Errorf("a violation with no rule id keyed %q, want no key (an unattributable block is no row)", got)
	}
}
