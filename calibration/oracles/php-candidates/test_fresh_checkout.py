"""Replay the suite with no pre-existing workspace, outside the working tree."""
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import unittest


class FreshCheckoutTests(unittest.TestCase):
    def test_suite_creates_its_workspace(self):
        repo = Path(__file__).resolve().parents[3]
        scratch = repo/'workspace/artifacts'
        scratch.mkdir(parents=True, exist_ok=True)
        with tempfile.TemporaryDirectory(dir=scratch) as temp:
            root = Path(temp)
            destination = root/'calibration/oracles/php-candidates'
            destination.mkdir(parents=True)
            here = Path(__file__).resolve().parent
            # Only recipe modules/tests are needed. Do not copy an existing
            # workspace, generated bytecode, or this recursive outer test.
            for source in here.glob('*.py'):
                if source.name != Path(__file__).name:
                    shutil.copyfile(source, destination/source.name)
            self.assertFalse((root/'workspace').exists())
            result = subprocess.run([sys.executable, '-B', '-m', 'unittest', 'discover',
                                     '-s', str(destination), '-p', 'test_*.py'],
                                    cwd=root, capture_output=True, text=True)
            self.assertEqual(result.returncode, 0, result.stdout+result.stderr)
            self.assertIn('Ran 16 tests', result.stderr)


if __name__ == '__main__':
    unittest.main()
