#!/usr/bin/env bash
# calibration/baseline.sh — measure today's extractors against the cloned corpus.
#
# For every repo cloned under workspace/calibration/, ingest it through the REAL
# fathom pipeline and report how many symbols each extractor finds, broken down by
# kind. Where a cheap language-appropriate proxy exists, also report a rough
# "expected definitions" count (grep-based) so the recall gap is visible. This is a
# proxy oracle, not ground truth — universal-ctags/SCIP give the real numbers later.
#
# Structural facts that need no oracle (already true by construction): only Go
# populates call edges and complexity, and every observation is stored at the
# 'verified' tier regardless of extractor. This script quantifies SYMBOL recall.
#
# Usage:
#   calibration/baseline.sh                       # all cloned repos
#   calibration/baseline.sh Python TypeScript     # only the named language dirs
#
# Requires: a built fathom binary (BIN env or workspace/tmp/fathom), git,
# and rg (ripgrep) for the proxy counts (optional — skipped if absent).
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CORPUS="$ROOT/workspace/calibration"
BIN="${BIN:-$ROOT/workspace/tmp/fathom}"
STORE="$ROOT/workspace/tmp/calibration.duckdb"
OUT="$ROOT/workspace/calibration/baseline-report.md"

[ -x "$BIN" ] || { echo "error: fathom binary not found at $BIN (set BIN= or run: CGO_ENABLED=1 go build -o workspace/tmp/fathom ./cmd/fathom)" >&2; exit 1; }
[ -d "$CORPUS" ] || { echo "error: no corpus at $CORPUS — run calibration/clone.sh first" >&2; exit 1; }
have_rg=0; command -v rg >/dev/null && have_rg=1

FILTERS=("$@")
want_dir() {
  [ ${#FILTERS[@]} -eq 0 ] && return 0
  local d_lc; d_lc="$(printf '%s' "$1" | tr '[:upper:]' '[:lower:]')"; local f
  for f in "${FILTERS[@]}"; do
    case "$d_lc" in *"$(printf '%s' "$f" | tr '[:upper:]' '[:lower:]')"*) return 0;; esac
  done
  return 1
}

# Rough "expected definitions" proxy per language slug. Pattern is an rg regex over
# the language's own file glob. Empty pattern => skip proxy (config/data formats).
# File-extension regex for the target language, so we count CODE symbols in the
# language's own files and exclude Markdown README doc-chunks (which otherwise
# dominate the count and inflate "recall"). Empty => count all symbols.
exts_for() {
  case "$1" in
    python)        echo '\.pyi?$';;
    javascript)    echo '\.(js|mjs|cjs|jsx)$';;
    typescript)    echo '\.(ts|tsx|mts|cts)$';;
    go)            echo '\.go$';;
    java)          echo '\.java$';;
    ruby)          echo '\.rb$';;
    rust)          echo '\.rs$';;
    php)           echo '\.php$';;
    terraform*)    echo '\.tf$';;
    *) : ;;
  esac
}

proxy_for() {  # echoes "<glob>\t<regex>" or nothing
  case "$1" in
    python)       printf '%s\t%s' '*.py'   '^\s*(async\s+)?def\s+\w+|^\s*class\s+\w+';;
    javascript)   printf '%s\t%s' '*.js'   '^\s*(export\s+)?(async\s+)?function\s+\w+|^\s*(export\s+)?class\s+\w+|=>\s*[{(]';;
    typescript)   printf '%s\t%s' '*.ts'   '^\s*(export\s+)?(async\s+)?function\s+\w+|^\s*(export\s+)?(abstract\s+)?class\s+\w+|^\s*(export\s+)?interface\s+\w+|^\s*(export\s+)?enum\s+\w+|^\s*(export\s+)?type\s+\w+';;
    go)           printf '%s\t%s' '*.go'   '^func\s|^type\s';;
    java)         printf '%s\t%s' '*.java' '^\s*(public|private|protected).*(class|interface|enum|record)\s+\w+|^\s*(public|private|protected).*\w+\s*\(';;
    ruby)         printf '%s\t%s' '*.rb'   '^\s*(class|module|def)\s+\w+';;
    rust)         printf '%s\t%s' '*.rs'   '^\s*(pub\s+)?(fn|struct|enum|trait|impl)\s+\w+';;
    php)          printf '%s\t%s' '*.php'  '^\s*(abstract\s+|final\s+)?(class|interface|trait|function)\s+\w+';;
    *) : ;;
  esac
}

{
  echo "# Calibration baseline — current extractors on real code"
  echo
  echo "Generated by calibration/baseline.sh. 'symbols' = what fathom extracts today."
  echo "'proxy' = rough grep-based expected-definition count (NOT ground truth)."
  echo "Recall ratio < 1 means the extractor is missing real symbols."
  echo
  echo "| Language | Repo | Files | Symbols (total) | Code syms (lang files) | Proxy defs | Recall (code/proxy) |"
  echo "|---|---|--:|--:|--:|--:|--:|"
} > "$OUT"

rm -f "$STORE"
for langdir in "$CORPUS"/*/; do
  [ -d "$langdir" ] || continue
  slug="$(basename "$langdir")"
  want_dir "$slug" || continue
  for repodir in "$langdir"*/; do
    [ -d "$repodir/.git" ] || continue
    repo="$(basename "$repodir")"
    svc="cal-$slug-$repo"
    nfiles=$(git -C "$repodir" ls-files | wc -l | tr -d ' ')
    # Ingest through the real pipeline.
    CGO_ENABLED=1 "$BIN" ingest --path "$repodir" --service "$svc" --store "$STORE" >/dev/null 2>&1 || { echo "  ingest failed: $svc" >&2; continue; }
    inspect_out=$("$BIN" inspect --service "$svc" --store "$STORE" 2>/dev/null || true)
    nsym=$(printf '%s\n' "$inspect_out" | awk -F': ' '/^symbols:/{n=$2} END{print n+0}')
    # Code symbols = symbols whose file path matches the target language's extensions.
    extrx="$(exts_for "$slug")"
    if [ -n "$extrx" ]; then
      ncode=$(printf '%s\n' "$inspect_out" | awk -v rx="$extrx" 'NF>=3 && $NF ~ rx {c++} END{print c+0}')
    else
      ncode="$nsym"
    fi
    proxy="-"; recall="-"
    if [ "$have_rg" = 1 ]; then
      spec="$(proxy_for "$slug" || true)"
      if [ -n "$spec" ]; then
        glob="${spec%%$'\t'*}"; rx="${spec#*$'\t'}"
        proxy=$(rg --no-messages -g "$glob" -c "$rx" "$repodir" 2>/dev/null | awk -F: '{s+=$2} END{print s+0}')
        if [ "${proxy:-0}" -gt 0 ]; then
          recall=$(awk -v a="$ncode" -v b="$proxy" 'BEGIN{printf "%.2f", a/b}')
        fi
      fi
    fi
    echo "| $slug | $repo | $nfiles | $nsym | $ncode | $proxy | $recall |" >> "$OUT"
    printf '%-14s %-20s files=%-5s total=%-6s code=%-6s proxy=%-6s recall=%s\n' "$slug" "$repo" "$nfiles" "$nsym" "$ncode" "$proxy" "$recall"
  done
done
rm -f "$STORE"

echo
echo "report written: $OUT"
