// TestIngest_GeneratedMinifiedGate pins LB-F10's wiring (design §5,
// ADR-048 §7): a dialect-owned file that is minified or carries a generator
// marker is fingerprinted, counted as skipped_generated and never
// extracted; the count reaches the Report and the service summary, and
// survives a re-ingest that reads nothing. A native extractor's generated
// file (a protoc-gen-go stub) is still extracted, tagged Generated, as
// ADR-021 §2 / TI-5 says.
func TestIngest_GeneratedMinifiedGate(t *testing.T) {
	dir := t.TempDir()
	writeFile(t, dir, "web/app.js", "function real() { return 1 }\n")
	writeFile(t, dir, "web/vendor.min.js", "function minified(){"+strings.Repeat("var a=1;", 200)+"}")
	writeFile(t, dir, "web/schema.ts", "/**\n * @generated\n */\nexport function gen() {}\n")
	writeFile(t, dir, "api/api.pb.go", "// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage api\n\nfunc Stub() {}\n")

	conn := connector.NewLocalConnector()
	st := store.NewMemoryStore()
	svc := core.ServiceRef{ID: "gate", Path: dir}
	p := fusion.New(conn, st, fusion.Config{Concurrency: 1})
	ctx := context.Background()
	report, err := p.Ingest(ctx, svc)
	if err != nil {
		t.Fatal(err)
	}
	if report.SkippedGenerated != 2 {
		t.Fatalf("Report.SkippedGenerated = %d, want 2", report.SkippedGenerated)
	}
	obs, err := st.QueryObservations(ctx, svc.ID, "")
	if err != nil {
		t.Fatal(err)
	}
	have := map[string]bool{}
	for _, o := range obs {
		have[o.SourceRef] = true
		if o.SourceRef == "api/api.pb.go" && !o.Generated {
			t.Errorf("pb.go observation not tagged Generated")
		}
	}
	for _, want := range []string{"web/app.js", "api/api.pb.go"} {
		if !have[want] {
			t.Errorf("%s not extracted", want)
		}
	}
	for _, skipped := range []string{"web/vendor.min.js", "web/schema.ts"} {
		if have[skipped] {
			t.Errorf("%s extracted, want skipped_generated", skipped)
		}
		if _, found, _ := st.Fingerprint(ctx, svc.ID, skipped); !found {
			t.Errorf("%s not fingerprinted", skipped)
		}
	}
	checkSummary := func(when string) {
		t.Helper()
		sum, ok, err := st.ServiceSummary(ctx, svc.ID)
		if err != nil || !ok {
			t.Fatalf("%s: ServiceSummary: ok=%v err=%v", when, ok, err)
		}
		if got := sum.ExcludedCounts[fusion.ExcludedSkippedGenerated]; got != 2 {
			t.Fatalf("%s: summary %s = %d, want 2 (%v)", when, fusion.ExcludedSkippedGenerated, got, sum.ExcludedCounts)
		}
	}
	checkSummary("first ingest")
	if _, err := p.Ingest(ctx, svc); err != nil {
		t.Fatal(err)
	}
	checkSummary("re-ingest")
}

// TestExtractForBench_SkipsGenerated: the harness scopes by the same gate
// (design §1: the oracle runs over exactly the files fathom reads).
func TestExtractForBench_SkipsGenerated(t *testing.T) {
	p := fusion.New(connector.NewLocalConnector(), store.NewMemoryStore(), fusion.Config{Concurrency: 1})
	got, err := p.ExtractForBench("s", nil, "a.min.js", []byte(strings.Repeat("x", 2000)))
	if err != nil {
		t.Fatal(err)
	}
	if got.Skipped != "generated" {
		t.Fatalf("Skipped = %q, want generated", got.Skipped)
	}
}
