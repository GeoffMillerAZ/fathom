// Oracle: task3.53.1 --taskfile <fixture> --list-all --json lists exactly
// check/gen/lock/update. Definitions/lines are retained in workspace/artifacts
// by the preparation lane; no task command is executed by that oracle.
const namedTaskFixture = `version: '3'
tasks:
  check:
    deps: [gen]
    cmds:
      - task: gen
  gen:
    cmds: [echo generated]
  lock:
    cmds:
      - task: update
  update:
    cmds: [echo updated]
`

func TestNamedToolAliasesDispatchWithoutBroadeningGenericFormats(t *testing.T) {
	p := New(connector.NewFauxConnector(), nil, Config{})
	t.Cleanup(p.Close)
	for _, path := range []string{"envkit.gen.yml", "taskfiles/envkit.gen.yml", "nested/tasks/envkit.gen.yml"} {
		if got := connector.ClassifyDialect(dialectRules(), path, []byte(namedTaskFixture)); got.Dialect != "taskfile" || got.By != connector.ClassifiedByBasename {
			t.Fatalf("%s: dialect = %+v, want taskfile by exact basename", path, got)
		}
		if got := connector.LanguageForPath(path); got != "taskfile" {
			t.Fatalf("%s: language = %s, want taskfile", path, got)
		}
		res, err := p.ExtractForBench("svc", nil, path, []byte(namedTaskFixture))
		if err != nil || res.Skipped != "" {
			t.Fatalf("%s: dispatch = %+v, %v", path, res, err)
		}
		var tasks []string
		for _, node := range res.Nodes {
			if string(node.Kind) == "TaskfileTask" {
				tasks = append(tasks, node.Name)
			}
		}
		sort.Strings(tasks)
		if !reflect.DeepEqual(tasks, []string{"check", "gen", "lock", "update"}) {
			t.Fatalf("%s: tasks = %v", path, tasks)
		}
	}
	// Hand-written Docker syntax oracle: FROM names one stage and ENV names
	// one declaration. The exact suffix aliases the existing tags engine.
	for _, path := range []string{"Dockerfile.context", "ci/Dockerfile.context"} {
		if got := connector.ClassifyDialect(dialectRules(), path, nil); got.Dialect != "dockerfile" || got.By != connector.ClassifiedByBasename {
			t.Fatalf("%s: dialect = %+v", path, got)
		}
		if got := connector.LanguageForPath(path); got != "dockerfile" {
			t.Fatalf("%s: language = %s", path, got)
		}
		res, err := p.ExtractForBench("svc", nil, path, []byte("FROM busybox:1 AS context\nENV MODE=review\n"))
		if err != nil || res.Skipped != "" {
			t.Fatalf("%s: dispatch = %+v, %v", path, res, err)
		}
		var kinds []string
		for _, node := range res.Nodes {
			kinds = append(kinds, string(node.Kind))
		}
		sort.Strings(kinds)
		if !reflect.DeepEqual(kinds, []string{"DockerStage", "DockerfileEnv"}) {
			t.Fatalf("%s: kinds = %v", path, kinds)
		}
	}
	for _, path := range []string{"taskfiles/config.yml", "taskfiles/other.gen.yml", "tasks/build.yml", "envkit.gen.yml.bak", "Dockerfile.context.bak", "notes.context", "Dockerfile.md"} {
		v := connector.ClassifyDialect(dialectRules(), path, nil)
		if v.Dialect == "taskfile" || v.Dialect == "dockerfile" {
			t.Fatalf("%s: unrelated file claimed: %+v", path, v)
		}
	}
	if got := connector.LanguageForPath("taskfiles/config.yml"); got != "yaml" {
		t.Fatalf("generic YAML became %s", got)
	}
	if got := connector.LanguageForPath("custom.dockerfile"); got != "dockerfile" {
		t.Fatalf("existing Docker syntax became %s", got)
	}
	for _, path := range []string{"envkit.gen.yml", "Dockerfile.context"} {
		res, err := p.ExtractForBench("svc", nil, path, []byte("# Code generated by fixture. DO NOT EDIT.\n"))
		if err != nil || res.Skipped != "generated" || len(res.Nodes) != 0 {
			t.Fatalf("%s: generated gate changed: %+v %v", path, res, err)
		}
	}
}

func TestNamedTaskfileIncludeResolvesItsActualAlias(t *testing.T) {
	files := docFiles(t, "taskfile", map[string]string{
		"Taskfile.yml":             "version: '3'\nincludes:\n  env: ./taskfiles/envkit.gen.yml\n",
		"taskfiles/envkit.gen.yml": namedTaskFixture,
	})
	want := []string{"Taskfile.yml:Taskfile.yml -includes-> taskfiles/envkit.gen.yml:envkit.gen.yml"}
	if got := xrefBrief(ResolveDocXrefs(files)); !reflect.DeepEqual(got, want) {
		t.Fatalf("got %v, want %v", got, want)
	}
}

// A prior unread fingerprint cannot permanently hide newly recognized paths.
func TestNamedToolAliasesInvalidatePriorUnreadFingerprints(t *testing.T) {
	dir := t.TempDir()
	ctx := context.Background()
	st := store.NewMemoryStore()
	svc := core.ServiceRef{ID: "named-tool-aliases", Path: dir}
	for name, src := range map[string]string{
		"taskfiles/envkit.gen.yml": namedTaskFixture,
		"ci/Dockerfile.context":    "FROM busybox:1 AS context\nENV MODE=review\n",
	} {
		path := filepath.Join(dir, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(src), 0o644); err != nil {
			t.Fatal(err)
		}
		old := sha256.Sum256(append([]byte(src), []byte("\x00fathom-extractor-epoch:65")...))
		if err := st.SetFingerprint(ctx, svc.ID, name, hex.EncodeToString(old[:])); err != nil {
			t.Fatal(err)
		}
	}
	p := New(connector.NewLocalConnector(), st, Config{Concurrency: 1})
	t.Cleanup(p.Close)
	rep, err := p.Ingest(ctx, svc)
	if err != nil {
		t.Fatal(err)
	}
	if rep.Skipped != 0 {
		t.Fatalf("%d prior unread files skipped; aliases need an epoch bump", rep.Skipped)
	}
	kinds := crSourceKinds(t, st, svc.ID)
	for file, kind := range map[string]string{"taskfiles/envkit.gen.yml": "TaskfileTask", "ci/Dockerfile.context": "DockerStage"} {
		if !crHasKind(kinds[file], kind) {
			t.Errorf("%s: got %v, want %s", file, kinds[file], kind)
		}
	}
}
