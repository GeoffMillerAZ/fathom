// TestAttributeHeaderLinguistBasesOverConvention (RF-3): a repository's
// .gitattributes (root and nested) outrank a file's header, which outranks
// its dialect, which outranks Linguist's pinned data, which outranks the
// convention table; a cleared attribute refuses its role at every weaker
// basis.
func TestAttributeHeaderLinguistBasesOverConvention(t *testing.T) {
	goGen := []byte("// Code generated by stringer -type=Kind; DO NOT EDIT.\n\npackage kind\n")
	kitGen := []byte("<!-- Code generated by cmd/kit-catalog; DO NOT EDIT. Regenerate: task docs-index -->\n\n# Catalog\n")
	plain := []byte("package x\n")
	fsys := fstest.MapFS{
		".gitattributes": {Data: []byte("# root\n" +
			"gen/** linguist-generated\n" +
			"vendor/ourlib/** -linguist-vendored\n" +
			"*.pb.go linguist-generated=true\n" +
			"examples/** linguist-documentation=false\n" +
			"kind_string.go -linguist-generated\n")},
		"web/.gitattributes": {Data: []byte("lib/** linguist-vendored\nlib/own.js !linguist-vendored\n")},
		"bad/.gitattributes": {Mode: fs.ModeDir},
	}
	cases := []struct {
		path, dialect string
		header        []byte
		want          Fact
	}{
		// attribute, root and nested, over everything weaker.
		{"gen/api.go", "go", plain, Fact{Generated, ByAttribute}},
		{"gen/api_test.go", "go", plain, Fact{Generated, ByAttribute}},
		{"internal/x/types.pb.go", "go", plain, Fact{Generated, ByAttribute}},
		{"web/lib/jquery.js", "js", nil, Fact{Vendored, ByAttribute}},
		{"web/lib/own.js", "js", nil, Fact{Source, ByConvention}},
		// a cleared attribute refuses its role at the weaker bases.
		{"vendor/ourlib/a.go", "go", plain, Fact{Source, ByConvention}},
		{"examples/demo.go", "go", plain, Fact{Source, ByConvention}},
		{"internal/kind/kind_string.go", "go", goGen, Fact{Source, ByConvention}},
		// header: Go's generated-code line, the O6 kit provenance header.
		{"internal/kind/zz_string.go", "go", goGen, Fact{Generated, ByHeader}},
		{"internal/kind/zz_string_test.go", "go", goGen, Fact{Generated, ByHeader}},
		{"docs/catalog.md", "md", kitGen, Fact{Generated, ByHeader}},
		// dialect over linguist: Linguist's vendor.yml lists .github/.
		{".github/workflows/ci.yml", "github-actions", nil, Fact{CI, ByDialect}},
		{".github/workflows/ci.yml", "yaml", nil, Fact{Vendored, ByLinguist}},
		// linguist over convention.
		{"package-lock.json", "json", nil, Fact{Generated, ByLinguist}},
		{"web/node_modules/left-pad/index.js", "js", nil, Fact{Vendored, ByLinguist}},
		{"docs/guide.md", "md", nil, Fact{Docs, ByLinguist}},
		{"web/types/index.d.ts", "ts", nil, Fact{Vendored, ByLinguist}},
		// convention when nothing stronger decides.
		{"internal/x/x.go", "go", plain, Fact{Source, ByConvention}},
		{"internal/x/x_test.go", "go", plain, Fact{Test, ByConvention}},
	}
	for _, c := range cases {
		attrs := ReadAttributes(fsys, c.path)
		if got := Role(c.path, c.dialect, attrs, c.header); got != c.want {
			t.Errorf("Role(%q, %q) = %v, want %v (attributes %+v)", c.path, c.dialect, got, c.want, attrs)
		}
	}
	if got := ReadAttributes(fsys, "bad/x.go").Unread; len(got) != 1 || got[0] != "bad/.gitattributes" {
		t.Errorf("an unreadable nested .gitattributes is unread %v, want it named (I38)", got)
	}
	if got := ReadAttributes(fstest.MapFS{}, "a/b.go"); got.role2() != "" || len(got.Unread) != 0 {
		t.Errorf("no .gitattributes declares %+v, want nothing", got)
	}
}

func (a Attributes) role2() RoleName { r, _ := a.role(); return r }

// TestLinguistDataPinnedWithLicence: the embedded linguist basis names its
// source, a 40-hex revision, the MIT licence and its copyright line, and
// names every upstream rule it left out.
func TestLinguistDataPinnedWithLicence(t *testing.T) {
	var d LinguistData
	if err := json.Unmarshal(linguistJSON, &d); err != nil {
		t.Fatal(err)
	}
	if d.Source != LinguistSource || d.Licence != "MIT" || d.Copyright == "" {
		t.Errorf("provenance = %q %q %q, want the source, MIT and the copyright line", d.Source, d.Licence, d.Copyright)
	}
	if !regexp.MustCompile(`^[0-9a-f]{40}$`).MatchString(d.Revision) || LinguistRevision() != d.Revision {
		t.Errorf("revision %q is not a pinned 40-hex commit", d.Revision)
	}
	if len(d.Vendor) == 0 || len(d.Documentation) == 0 || len(d.Generated) == 0 || len(d.Dropped) == 0 {
		t.Errorf("data counts vendor %d documentation %d generated %d dropped %d", len(d.Vendor), len(d.Documentation), len(d.Generated), len(d.Dropped))
	}
}

// TestImportLinguistKeepsPathRulesDropsTheRest: the importer keeps a
// pattern RE2 compiles and a generated.rb detector that tests only the
// path, and drops (and names) a lookbehind and a detector that reads
// content.
func TestImportLinguistKeepsPathRulesDropsTheRest(t *testing.T) {
	vendor := []byte("- (^|/)node_modules/\n- vendor/(?<!-)x\n")
	docs := []byte("- ^[Dd]ocs?/\n")
	rb := []byte(`module Linguist
  class Generated
    def generated?
      xcode_file? ||
      cargo_lock? ||
      generated_go?
    end

    def xcode_file?
      ['.nib', '.xcuserstate'].include?(extname)
    end

    def cargo_lock?
      !!name.match(/Cargo\.lock/)
    end

    def generated_go?
      return false unless extname == '.go'
      return lines.first(40).any? { |l| l =~ %r{^// Code generated .*} }
    end
  end
end
`)
	licence := []byte("Copyright (c) 2017 GitHub, Inc.\n\nPermission is hereby granted, free of charge, to any person\n")
	if _, err := ImportLinguist(vendor, docs, rb, licence, "abc"); err == nil {
		t.Error("a revision that is not 40 hex imported")
	}
	d, err := ImportLinguist(vendor, docs, rb, licence, "5fbdfcb8133be2bed88bf3ce62b2335f50474525")
	if err != nil {
		t.Fatal(err)
	}
	if len(d.Vendor) != 1 || len(d.Documentation) != 1 || len(d.Generated) != 2 {
		t.Errorf("kept vendor %v documentation %v generated %v", d.Vendor, d.Documentation, d.Generated)
	}
	if len(d.Dropped) != 2 {
		t.Errorf("dropped %+v, want the lookbehind and the content detector", d.Dropped)
	}
	if !regexp.MustCompile(d.Generated[0]).MatchString("App.xcuserstate") {
		t.Errorf("extension list rendered %q", d.Generated[0])
	}
}
