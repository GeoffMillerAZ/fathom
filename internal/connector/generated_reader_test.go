package connector_test

import (
	"bytes"
	"errors"
	"fmt"
	"io"
	"strings"
	"testing"

	"github.com/geoffmilleraz/fathom/internal/connector"
)

type countingReader struct {
	r     *bytes.Reader
	bytes int
}

func (r *countingReader) Read(p []byte) (int, error) {
	n, err := r.r.Read(p)
	r.bytes += n
	return n, err
}

type shortReader struct{ data []byte }

func (r *shortReader) Read(p []byte) (int, error) {
	if len(r.data) == 0 {
		return 0, io.EOF
	}
	n := copy(p, r.data[:min(3, len(r.data))])
	r.data = r.data[n:]
	return n, nil
}

type failingReader struct{}

func (failingReader) Read([]byte) (int, error) { return 0, errors.New("read failed") }

type partialFailingReader struct{ done bool }

func (r *partialFailingReader) Read(p []byte) (int, error) {
	if r.done {
		return 0, errors.New("read failed")
	}
	r.done = true
	return copy(p, "# Code generated by fixture. DO NOT EDIT."), errors.New("read failed")
}

func TestIsGeneratedReaderMatchesFullClassifier(t *testing.T) {
	long := "# " + strings.Repeat("x", 100000) + " Code generated by fixture. DO NOT EDIT.\n"
	cases := []struct{ path, body string }{
		{"asset.png", strings.Repeat("x", 200000)},
		{"config.yaml", long + "normal\n"},
		{"config.yaml", "# first\n# second\n" + long},
		{"config.yaml", "# first\n# second\n# third\n" + long},
		{"config.yaml", "# Code generated by fixture. DO NOT EDITOR\n"},
		{"config.yaml", "# Code generated by fixture. dO nOt EdIt.\n"},
		{"config.yaml", "# Code generated by fixture. DO NOT EDIT" + strings.Repeat("x", 70000) + "\n"},
		{"config.yaml", "# Code generated by fixture. DO NOT EDIT" + strings.Repeat(" ", 70000) + "\n"},
		{"config.yaml", "# Code generated by fixture. DO NOT EDIT" + strings.Repeat(" ", 70000) + "E\n"},
		{"config.yaml", "# " + strings.Repeat("x", 65530) + " Code generated by fixture. DO NOT EDIT.\n"},
		{"config.yaml", "# " + strings.Repeat("λ", 32764) + " Code generated by fixture. dO nOt EdIt.\n"},
		{"config.yaml", "# Code generated by fixture. " + strings.Repeat("x", 65512) + " DO NOT EDIT.\n"},
		{"config.yaml", "value: Code generated by fixture. DO NOT EDIT.\n"},
		{"docs/readme.md", "<!-- Code generated by fixture. DO NOT EDIT. -->\n"},
		{"main.go", strings.Repeat("// license\n", 100) + "// Code generated by tool. DO NOT EDIT.\npackage main\n"},
		{"main.go", "package main\n// Code generated by tool. DO NOT EDIT.\n"},
		{"main.go", strings.Repeat("x", 4096) + "\n// Code generated by tool. DO NOT EDIT.\n"},
	}
	for i, c := range cases {
		t.Run(fmt.Sprintf("%s/%d", c.path, i), func(t *testing.T) {
			got, err := connector.IsGeneratedReader(c.path, &shortReader{data: []byte(c.body)})
			if err != nil || got != connector.IsGenerated(c.path, []byte(c.body)) {
				t.Fatalf("streamed=%v err=%v, full=%v", got, err, connector.IsGenerated(c.path, []byte(c.body)))
			}
		})
	}
}

func TestIsGeneratedReaderReportsReadError(t *testing.T) {
	for _, path := range []string{"main.go", "config.yaml"} {
		if got, err := connector.IsGeneratedReader(path, failingReader{}); got || err == nil {
			t.Fatalf("%s: got %v, err %v", path, got, err)
		}
	}
	if got, err := connector.IsGeneratedReader("config.yaml", &partialFailingReader{}); got || err == nil {
		t.Fatalf("partial failure: got %v, err %v", got, err)
	}
}

func TestIsGeneratedReaderBoundsHeaderRead(t *testing.T) {
	goBody := []byte("package main\n" + strings.Repeat("x", 4<<20))
	goReader := &countingReader{r: bytes.NewReader(goBody)}
	if generated, err := connector.IsGeneratedReader("main.go", goReader); err != nil || generated || goReader.bytes != 4096 {
		t.Fatalf("Go generated=%v err=%v bytes=%d", generated, err, goReader.bytes)
	}
	yamlBody := []byte("# first\n# second\n# third\n" + strings.Repeat("x", 4<<20))
	yamlReader := &countingReader{r: bytes.NewReader(yamlBody)}
	if generated, err := connector.IsGeneratedReader("config.yaml", yamlReader); err != nil || generated || yamlReader.bytes > 4*1024 {
		t.Fatalf("YAML generated=%v err=%v bytes=%d", generated, err, yamlReader.bytes)
	}
}
