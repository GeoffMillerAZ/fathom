func writeTree(t *testing.T, files map[string]string) string {
	t.Helper()
	root := t.TempDir()
	for rel, body := range files {
		p := filepath.Join(root, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return root
}

// snapshot reads every regular file under root, keyed by slash path.
func snapshot(t *testing.T, root string) map[string]string {
	t.Helper()
	out := map[string]string{}
	err := filepath.WalkDir(root, func(p string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		b, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		rel, _ := filepath.Rel(root, p)
		out[filepath.ToSlash(rel)] = string(b)
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	return out
}

func diffTrees(a, b map[string]string) []string {
	var d []string
	for k, v := range a {
		if w, ok := b[k]; !ok {
			d = append(d, "only before: "+k)
		} else if v != w {
			d = append(d, "differs: "+k)
		}
	}
	for k := range b {
		if _, ok := a[k]; !ok {
			d = append(d, "only after: "+k)
		}
	}
	sort.Strings(d)
	return d
}

// TestRewriteRoundTrip is DS-2: forward then reverse restores the tree byte
// for byte, both for the whole repository and for one kit copy alone (the
// shape sync-kit and vendor-check rewrite).
func TestRewriteRoundTrip(t *testing.T) {
	root := writeTree(t, fixture())
	before := snapshot(t, root)

	fwd, err := RewriteRepo(root, Forward)
	if err != nil {
		t.Fatal(err)
	}
	if fwd.Imports == 0 || fwd.Moved == 0 {
		t.Fatalf("forward rewrote nothing: %+v", fwd)
	}
	mid := snapshot(t, root)
	if len(diffTrees(before, mid)) == 0 {
		t.Fatal("forward left the tree unchanged")
	}
	rev, err := RewriteRepo(root, Reverse)
	if err != nil {
		t.Fatal(err)
	}
	if rev != fwd {
		t.Errorf("reverse report %+v, forward %+v: a round trip touches the same files", rev, fwd)
	}
	if d := diffTrees(before, snapshot(t, root)); len(d) != 0 {
		t.Fatalf("round trip is not byte-identical:\n%s", strings.Join(d, "\n"))
	}

	kit := filepath.Join(root, "third_party", "agentic-kit")
	if _, err := RewriteKit(kit, testModule, Forward); err != nil {
		t.Fatal(err)
	}
	if _, err := RewriteKit(kit, testModule, Reverse); err != nil {
		t.Fatal(err)
	}
	if d := diffTrees(before, snapshot(t, root)); len(d) != 0 {
		t.Fatalf("kit round trip is not byte-identical:\n%s", strings.Join(d, "\n"))
	}
}

// TestRewriteForwardShape pins what forward changes and what it leaves alone.
func TestRewriteForwardShape(t *testing.T) {
	root := writeTree(t, fixture())
	if _, err := RewriteRepo(root, Forward); err != nil {
		t.Fatal(err)
	}
	got := snapshot(t, root)
	internalAK := testModule + "/third_party/agentic-kit"
	internalApp := testModule + "/third_party/app-kit"
	for rel, want := range map[string]string{
		"cmd/app/main.go":                                   "ak \"" + internalAK + "/foundations/decision\"",
		"internal/x/x.go":                                   "import \"" + internalAK + "\"",
		"internal/x/single.go":                              "import _ \"" + internalApp + "/appkit\" // side effect",
		"cmd/app/ui/page.templ":                             "\"" + internalApp + "/appkit/ui/card\"",
		"cmd/app/ui/page_templ.go":                          "import \"" + internalApp + "/appkit/ui/card\"",
		"third_party/agentic-kit/foundations/decision/d.go": "\"" + internalAK + "/foundations/llmclient\" // the client",
		"third_party/app-kit/appkit/ui/card/card.go":        "\"" + internalApp + "/appkit\"",
		"third_party/app-kit/appkit/ui/table/table.templ":   "import \"" + internalApp + "/appkit/ui/card\"",
		"third_party/agentic-kit/go.mod.upstream":           "module github.com/geoffmilleraz/agentic-kit",
		"third_party/agentic-kit/go.work.upstream":          "./kits/pdf",
		"third_party/app-kit/go.sum.upstream":               "example.com/dep",
	} {
		if !strings.Contains(got[rel], want) {
			t.Errorf("%s: want %q in\n%s", rel, want, got[rel])
		}
	}
	// Untouched: a non-import string, a raw-string fixture in a test, testdata,
	// a nested module, dot and workspace directories, a lookalike path.
	for _, rel := range []string{
		"internal/x/strings.go", "internal/x/testdata/f.go", "internal/x/lookalike.go",
		"calibration/nested/n.go", ".claude/worktrees/w/w.go", "workspace/tmp/scratch.go",
		"third_party/agentic-kit/foundations/decision/d_test.go",
		"third_party/agentic-kit/cmd/kit-new/testdata/golden/main.go",
		"third_party/agentic-kit/kits/pdf/pdf.go", "third_party/agentic-kit/kits/pdf/go.mod",
	} {
		if got[rel] != fixture()[rel] {
			t.Errorf("%s changed:\n%s", rel, got[rel])
		}
	}
	for _, gone := range []string{
		"third_party/agentic-kit/go.mod", "third_party/agentic-kit/go.work", "third_party/agentic-kit/go.work.sum",
		"third_party/app-kit/go.mod", "third_party/app-kit/go.sum",
	} {
		if _, ok := got[gone]; ok {
			t.Errorf("%s still present: a mirror with a go.mod stays a nested module", gone)
		}
	}
}

// TestRewriteIdempotent: a second forward pass changes nothing.
func TestRewriteIdempotent(t *testing.T) {
	root := writeTree(t, fixture())
	if _, err := RewriteRepo(root, Forward); err != nil {
		t.Fatal(err)
	}
	once := snapshot(t, root)
	again, err := RewriteRepo(root, Forward)
	if err != nil {
		t.Fatal(err)
	}
	if again.Imports != 0 || again.Moved != 0 || again.Files != 0 {
		t.Errorf("second forward pass reported work: %+v", again)
	}
	if d := diffTrees(once, snapshot(t, root)); len(d) != 0 {
		t.Fatalf("second forward pass changed the tree:\n%s", strings.Join(d, "\n"))
	}
}

// TestRewriteRefusesBothForms: a mirror holding go.mod AND go.mod.upstream is
// ambiguous (a half-synced copy); the rewrite names it rather than pick one.
func TestRewriteRefusesBothForms(t *testing.T) {
	files := fixture()
	files["third_party/app-kit/go.mod.upstream"] = "module github.com/geoffmilleraz/app-kit\n"
	root := writeTree(t, files)
	if _, err := RewriteRepo(root, Forward); err == nil || !strings.Contains(err.Error(), "go.mod.upstream") {
		t.Fatalf("want an error naming go.mod.upstream, got %v", err)
	}
}

// TestCheckFixture: Check names each way a tree is not self-contained.
func TestCheckFixture(t *testing.T) {
	root := writeTree(t, fixture())
	vs, err := Check(root)
	if err != nil {
		t.Fatal(err)
	}
	joined := strings.Join(vs, "\n")
	for _, want := range []string{
		"third_party/agentic-kit/go.mod: a mirror with its own go.mod is a nested module",
		"cmd/app/main.go:6: imports github.com/geoffmilleraz/agentic-kit/foundations/decision",
		"third_party/app-kit/appkit/ui/table/table.templ:3: imports github.com/geoffmilleraz/app-kit/appkit/ui/card",
	} {
		if !strings.Contains(joined, want) {
			t.Errorf("Check missed %q in:\n%s", want, joined)
		}
	}
	if _, err := RewriteRepo(root, Forward); err != nil {
		t.Fatal(err)
	}
	if vs, err := Check(root); err != nil || len(vs) != 0 {
		t.Fatalf("after forward: %v %v", vs, err)
	}

	gomod := filepath.Join(root, "go.mod")
	for _, c := range []struct{ line, want string }{
		{"replace example.com/dep => ../dep\n", "go.mod: replace example.com/dep"},
		{"exclude example.com/dep v1.0.0\n", "go.mod: exclude example.com/dep v1.0.0"},
		{"require example.com/owner/kit v0.1.0\n", "go.mod: requires example.com/owner/kit"},
	} {
		if err := os.WriteFile(gomod, []byte("module "+testModule+"\n\ngo 1.26\n\n"+c.line), 0o644); err != nil {
			t.Fatal(err)
		}
		vs, err := Check(root)
		if err != nil {
			t.Fatal(err)
		}
		if len(vs) != 1 || !strings.Contains(vs[0], c.want) {
			t.Errorf("%q: got %v, want one violation containing %q", c.line, vs, c.want)
		}
	}
}

// TestRepositoryIsSelfContained is DS-1 on this repository: go.mod carries no
// replace, no exclude and no requirement of a module under fathom's own
// owner path (private siblings the proxy cannot serve), each kit mirror is a
// plain directory of this module, and no Go or templ file outside testdata
// and nested modules imports a kit by its upstream path.
func TestRepositoryIsSelfContained(t *testing.T) {
	_, file, _, _ := runtime.Caller(0)
	root := filepath.Clean(filepath.Join(filepath.Dir(file), "..", ".."))
	vs, err := Check(root)
	if err != nil {
		t.Fatal(err)
	}
	if len(vs) != 0 {
		t.Fatalf("fathom is not one self-contained module (ADR-070); run `go run ./cmd/kitrewrite`:\n%s", strings.Join(vs, "\n"))
	}
}
