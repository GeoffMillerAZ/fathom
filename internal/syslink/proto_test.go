package syslink

import "testing"

const ordersProto = `syntax = "proto3";
package shop.v1;

service Orders {
  rpc Create(CreateRequest) returns (Order);
  rpc Get(GetRequest) returns (Order);
}
`

// A generated stub, reduced to the shapes protoc-gen-go-grpc emits.
const ordersStub = `// Code generated by protoc-gen-go-grpc. DO NOT EDIT.

package shopv1

import grpc "google.golang.org/grpc"

const (
	Orders_Create_FullMethodName = "/shop.v1.Orders/Create"
	Orders_Get_FullMethodName    = "/shop.v1.Orders/Get"
)

type OrdersClient interface{}

type ordersClient struct{ cc grpc.ClientConnInterface }

func NewOrdersClient(cc grpc.ClientConnInterface) OrdersClient { return &ordersClient{cc} }
`

const ordersConsumer = `package checkout

import shopv1 "example/gen/shop/v1"

func Place(conn any) {
	c := shopv1.NewOrdersClient(conn)
	c.Create(ctx, req)
	c.Delete(ctx, req) // not an RPC of Orders: nothing
	other.Create(ctx, req)
}

func Look(conn any) {
	shopv1.NewOrdersClient(conn).Get(ctx, req)
}
`

// TestProtoProvidesAndStubConsumes is SG-8's contract: proto service
// definitions provide rpc: keys at spec tier, and Go gRPC client calls,
// resolved through the generated stub's full method names, consume them at
// typed tier; a call the stub does not resolve consumes nothing.
func TestProtoProvidesAndStubConsumes(t *testing.T) {
	files := []SourceFile{
		{Path: "api/orders.proto", Dialect: "proto", Content: []byte(ordersProto)},
		{Path: "gen/shop/v1/orders_grpc.pb.go", Dialect: "go", Content: []byte(ordersStub)},
		{Path: "checkout/place.go", Dialect: "go", Content: []byte(ordersConsumer)},
	}
	checkRows(t, "proto", protoRPCKeys(files), []rowWant{
		{"rpc:shop.v1.Orders/Create", "provides", "shop.v1.Orders/Create", TierSpec, 5},
		{"rpc:shop.v1.Orders/Get", "provides", "shop.v1.Orders/Get", TierSpec, 6},
		{"rpc:shop.v1.Orders/Create", "consumes", "Place", TierTyped, 7},
		{"rpc:shop.v1.Orders/Get", "consumes", "Look", TierTyped, 13},
	})

	// Without the generated stub nothing resolves the consumer: provides only.
	noStub := []SourceFile{files[0], files[2]}
	for _, r := range protoRPCKeys(noStub) {
		if r.Role == RoleConsumes {
			t.Errorf("consumer resolved without a stub: %+v", r)
		}
	}

	// The per-file source serves the provides half by dialect id.
	if rows := fileSources(t).Keys("api/orders.proto", []byte(ordersProto), "proto"); len(rows) != 2 {
		t.Errorf("registry proto rows = %v", rows)
	}
}
