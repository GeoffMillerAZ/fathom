package mcp

import (
	"testing"

	"github.com/geoffmilleraz/fathom/internal/core"
)

// TestSearchAndSymbolContextNameRoleAndBasis (RF-4): search names each
// hit's file role and the basis that decided it and counts the answer's
// unknown files (I65), and symbol_context on a file path answers the
// file's role block, through the tools that exist (no new tool, no new
// parameter).
func TestSearchAndSymbolContextNameRoleAndBasis(t *testing.T) {
	root := t.TempDir()
	writeFlagFixture(t, root, ".gitattributes", "gen/** linguist-generated\n")
	writeFlagFixture(t, root, "pkg/a.go", "package pkg\n\nfunc Needle() {}\n")
	writeFlagFixture(t, root, "pkg/a_test.go", "package pkg\n\n// Needle is tested here.\nfunc TestNeedle() {}\n")
	writeFlagFixture(t, root, "gen/api.go", "package gen\n\n// Needle\n")
	writeFlagFixture(t, root, "zz/kind_string.go", "// Code generated by stringer; DO NOT EDIT.\n\npackage zz\n\n// Needle\n")
	writeFlagFixture(t, root, "scripts/run.sh", "#!/bin/sh\necho Needle\n")
	writeFlagFixture(t, root, "data/blob.xyz", "Needle\n")

	backend := &searchIgnoreTestBackend{
		elisionFakeBackend: elisionFakeBackend{nodes: []core.SymbolNode{
			{Service: "svc", Package: "pkg", Name: "Needle", Kind: core.KindGoFunc, FilePath: "pkg/a.go", Line: 3},
			{Service: "svc", Package: "pkg", Name: "TestNeedle", Kind: core.KindGoFunc, FilePath: "pkg/a_test.go", Line: 4},
		}},
		svcPath: root,
	}
	srv := NewServer(backend)

	res := callTool(t, srv, "search", map[string]any{"service": "svc", "pattern": "Needle"})
	want := map[string]string{
		"pkg/a.go":          "source/convention",
		"pkg/a_test.go":     "test/convention",
		"gen/api.go":        "generated/attribute",
		"zz/kind_string.go": "generated/header",
		"scripts/run.sh":    "script/convention",
		"data/blob.xyz":     "unknown",
	}
	hits, _ := res["hits"].([]any)
	seen := map[string]bool{}
	for _, raw := range hits {
		h := raw.(map[string]any)
		loc, _ := h["loc"].(string)
		file := loc
		for i := 0; i < len(loc); i++ {
			if loc[i] == ':' {
				file = loc[:i]
				break
			}
		}
		seen[file] = true
		if got, _ := h["role"].(string); got != want[file] {
			t.Errorf("search hit %s role = %q, want %q", loc, got, want[file])
		}
	}
	for f := range want {
		if !seen[f] {
			t.Errorf("search: no hit in %s (hits %v)", f, hits)
		}
	}
	if got, ok := res["role_unknown"].(float64); !ok || got != 1 {
		t.Errorf("search role_unknown = %v (present %v), want 1 printed (I65)", res["role_unknown"], ok)
	}

	for path, wantRole := range map[string][2]any{
		"pkg/a_test.go":  {"test", "convention"},
		"scripts/run.sh": {"script", "convention"},
		"gen/api.go":     {"generated", "attribute"},
		"data/blob.xyz":  {"unknown", nil},
	} {
		sc := callTool(t, srv, "symbol_context", map[string]any{"service": "svc", "symbol": path})
		file, ok := sc["file"].(map[string]any)
		if !ok {
			t.Fatalf("symbol_context %s: no file block: %v", path, sc)
		}
		if file["path"] != path || file["role"] != wantRole[0] || file["basis"] != wantRole[1] {
			t.Errorf("symbol_context %s file = %v, want role %v basis %v", path, file, wantRole[0], wantRole[1])
		}
		wantUnknown := 0.0
		if wantRole[0] == "unknown" {
			wantUnknown = 1
		}
		if got, ok := file["role_unknown"].(float64); !ok || got != wantUnknown {
			t.Errorf("symbol_context %s role_unknown = %v, want %v printed (I65)", path, file["role_unknown"], wantUnknown)
		}
	}
	// The block both tools serve is fileRoleBlock's: path, dialect,
	// .gitattributes chain and head through repofacts.Role.
	if fact, attrs := fileRoleBlock(root, "gen/api.go", nil); fact.String() != "generated/attribute" || len(attrs.Unread) != 0 {
		t.Errorf("fileRoleBlock(gen/api.go) = %v %+v, want generated/attribute", fact, attrs)
	}
	if fact, _ := fileRoleBlock("", "pkg/a_test.go", nil); fact.String() != "test/convention" {
		t.Errorf("fileRoleBlock with no root = %v, want the path bases alone: test/convention", fact)
	}
	// A symbol query keeps its neighbourhood answer and serves no file block.
	if sc := callTool(t, srv, "symbol_context", map[string]any{"service": "svc", "symbol": "Needle", "snippet": false}); sc["file"] != nil || sc["def"] == nil {
		t.Errorf("symbol_context on a symbol = %v, want its def and no file block", sc)
	}
	// A path outside the corpus is no file of the service.
	if sc := callTool(t, srv, "symbol_context", map[string]any{"service": "svc", "symbol": "../etc/passwd"}); sc["file"] != nil {
		t.Errorf("symbol_context on an escaping path served a file block: %v", sc)
	}
}
