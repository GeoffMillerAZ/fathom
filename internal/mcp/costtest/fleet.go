// Package costtest is the per-tool cost harness (design §4.8; plan RT-93,
// RT-94, RT-95): every registered MCP tool, called cold and warm against a
// generated fleet at 1× and 10×, measured for bytes read (the admission
// meter) and heap allocations (runtime/metrics /gc/heap/allocs:bytes), and
// the cold-stampede measurements (one build and one walk per key; callers
// cancelled leave no goroutine behind).
//
// It is a test harness in a package of its own so the measurement sits
// outside the code it measures; nothing in the daemon imports it.
package costtest

import (
	"context"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/geoffmilleraz/fathom/internal/connector"
	"github.com/geoffmilleraz/fathom/internal/core"
	"github.com/geoffmilleraz/fathom/internal/indexbench"
	"github.com/geoffmilleraz/fathom/internal/store"
	"github.com/geoffmilleraz/fathom/pkg/client"
)

// QueriedService is the service every service-scoped row asks about. It is
// the same size at every scale: the fleet grows around it (I48 — a point
// or index answer's cost follows the answer, not the fleet).
const QueriedService = "ledger-service"

// BulkFuncs is how many generated functions each Go service carries beside
// its fauxtown sources, so a per-service cost is large enough to see.
const BulkFuncs = 200

// Fleet is one generated fleet, ingested into a memory store.
type Fleet struct {
	Scale    int
	Root     string
	Store    *store.MemoryStore
	Conn     *connector.LocalConnector
	Services []string
}

// NewClient is a fresh client over the fleet's store: its own store
// identity, so every memo key it touches is cold.
func (f *Fleet) NewClient() *client.Client { return client.New(f.Conn, f.Store) }

// fauxtownServices are the fixture's services, copied once per replica.
var fauxtownServices = []string{"catalog-service", "checkout-service", "ledger-service", "payment-service", "polyglot-service", "worktree-service"}

// BuildFleet writes the fauxtown services scale times under dir (the first
// copy keeps each service's name, later copies are "<name>-r<N>"), adds
// BulkFuncs generated functions to every Go service, and a 12 MiB text file
// and a binary blob to the queried service, then ingests them all.
func BuildFleet(ctx context.Context, dir string, scale int) (*Fleet, error) {
	if scale < 1 {
		return nil, fmt.Errorf("costtest: scale %d", scale)
	}
	src := indexbench.FauxtownRoot()
	f := &Fleet{Scale: scale, Root: dir, Store: store.NewMemoryStore(), Conn: connector.NewLocalConnector()}
	for r := 1; r <= scale; r++ {
		for _, svc := range fauxtownServices {
			name := svc
			if r > 1 {
				name = fmt.Sprintf("%s-r%02d", svc, r)
			}
			if err := copyService(filepath.Join(src, svc), filepath.Join(dir, name)); err != nil {
				return nil, err
			}
			f.Services = append(f.Services, name)
		}
	}
	queried := filepath.Join(dir, QueriedService)
	big := make([]byte, 12<<20)
	for i := range big {
		big[i] = 'a' + byte(i%26)
		if i%80 == 79 {
			big[i] = '\n'
		}
	}
	if err := os.WriteFile(filepath.Join(queried, "big.txt"), big, 0o644); err != nil {
		return nil, err
	}
	blob := make([]byte, 64<<10)
	for i := range blob {
		blob[i] = byte(i * 7)
	}
	if err := os.WriteFile(filepath.Join(queried, "blob.bin"), blob, 0o644); err != nil {
		return nil, err
	}
	c := f.NewClient()
	for _, svc := range f.Services {
		if _, err := c.Ingest(ctx, core.ServiceRef{ID: svc, Path: filepath.Join(dir, svc)}); err != nil {
			return nil, fmt.Errorf("costtest: ingest %s: %w", svc, err)
		}
	}
	return f, nil
}

// copyService copies one fixture service and, when it holds Go sources,
// adds bulk.go in the same package.
func copyService(from, to string) error {
	if err := os.MkdirAll(to, 0o755); err != nil {
		return err
	}
	entries, err := os.ReadDir(from)
	if err != nil {
		return err
	}
	pkg := ""
	for _, e := range entries {
		if e.IsDir() {
			continue
		}
		b, err := os.ReadFile(filepath.Join(from, e.Name()))
		if err != nil {
			return err
		}
		if strings.HasSuffix(e.Name(), ".go") && pkg == "" {
			pkg = packageName(string(b))
		}
		if err := os.WriteFile(filepath.Join(to, e.Name()), b, 0o644); err != nil {
			return err
		}
	}
	if pkg == "" {
		return nil
	}
	return os.WriteFile(filepath.Join(to, "bulk.go"), []byte(bulkSource(pkg)), 0o644)
}

func packageName(src string) string {
	for _, l := range strings.Split(src, "\n") {
		if name, ok := strings.CutPrefix(strings.TrimSpace(l), "package "); ok {
			return strings.TrimSpace(name)
		}
	}
	return ""
}

// bulkSource is BulkFuncs functions in a call chain, each with a comment
// and a few statements, deterministic.
func bulkSource(pkg string) string {
	var b strings.Builder
	fmt.Fprintf(&b, "package %s\n\n// Generated by internal/mcp/costtest: cost-harness bulk.\n\n", pkg)
	for i := 0; i < BulkFuncs; i++ {
		fmt.Fprintf(&b, "// bulkStep%03d is step %d of the generated chain.\nfunc bulkStep%03d(n int) int {\n\tif n <= 0 {\n\t\treturn %d\n\t}\n", i, i, i, i)
		if i > 0 {
			fmt.Fprintf(&b, "\treturn bulkStep%03d(n-1) + %d\n}\n\n", i-1, i)
		} else {
			fmt.Fprintf(&b, "\treturn n + %d\n}\n\n", i)
		}
	}
	return b.String()
}
