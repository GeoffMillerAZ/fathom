package integrity

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func writeDeclFile(t *testing.T, dir, rel, data string) {
	t.Helper()
	p := filepath.Join(dir, filepath.FromSlash(rel))
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(data), 0o644); err != nil {
		t.Fatal(err)
	}
}

// TestGeneratedHandEditsReadsDeclarationsFirst is FD-16's anchor: the
// project pack's and the discovered tech packs' `generated` declarations are
// read before the same-directory heuristic. A declared output edited without
// its declared source is a finding citing the declaration, even where the
// heuristic would stay silent (no generated header) or call it clean (an
// unrelated same-directory .cue changed); a declared output whose source
// changed is clean; the heuristic still runs for what no declaration covers.
func TestGeneratedHandEditsReadsDeclarationsFirst(t *testing.T) {
	base := t.TempDir()
	root := filepath.Join(base, "repo")
	cache := filepath.Join(base, "gomodcache")
	t.Setenv("GOMODCACHE", cache)
	t.Setenv("CUE_CACHE_DIR", filepath.Join(base, "cuecache"))
	t.Setenv("GOPROXY", "off")

	writeDeclFile(t, root, ".fathom/pack.cue",
		"generated: [{output: \"ui/app.css\", source: [\"ui/input.css\"], regenerate: \"task ui:css\"}]\n")
	writeDeclFile(t, root, "go.mod", "module example.test/app\n\ngo 1.22\n\nrequire example.test/tmplkit v1.0.0\n")
	writeDeclFile(t, cache, "example.test/tmplkit@v1.0.0/fathom-pack/pack.cue",
		"pack: {name: \"tmpl-kit\", version: 1, about: \"templates\"}\n"+
			"generated: [{output: \"{dir}/{name}_templ.go\", source: [\"{dir}/{name}.templ\"], regenerate: \"templ generate\"}]\n")

	const hdr = "// Code generated by templ - DO NOT EDIT.\n"
	baseFiles := map[string][]byte{
		"ui/app.css":          []byte(".a{}\n"),
		"ui/input.css":        []byte("@import x;\n"),
		"views/home_templ.go": []byte(hdr + "package views\nvar A = 1\n"),
		"views/home.templ":    []byte("package views\n"),
		"views/schema.cue":    []byte("a: 1\n"),
		"views/page_templ.go": []byte(hdr + "package views\nvar B = 1\n"),
		"views/page.templ":    []byte("package views\n"),
		"root_templ.go":       []byte(hdr + "package app\nvar C = 1\n"),
		"root.templ":          []byte("package app\n"),
		"api/x.pb.go":         []byte(goGenHeader + "package api\nvar D = 1\n"),
		"api/x.proto":         []byte("syntax = \"proto3\";\n"),
	}
	headFiles := map[string][]byte{}
	for k, v := range baseFiles {
		headFiles[k] = v
	}
	headFiles["ui/app.css"] = []byte(".a{color:red}\n")                           // hand edit, no header
	headFiles["views/home_templ.go"] = []byte(hdr + "package views\nvar A = 2\n") // hand edit
	headFiles["views/schema.cue"] = []byte("a: 2\n")                              // fools the heuristic, not the declaration
	headFiles["views/page_templ.go"] = []byte(hdr + "package views\nvar B = 2\n") // regenerated
	headFiles["views/page.templ"] = []byte("package views\n// changed\n")
	headFiles["root_templ.go"] = []byte(hdr + "package app\nvar C = 2\n") // {dir} binds the root
	headFiles["api/x.pb.go"] = []byte(goGenHeader + "package api\nvar D = 2\n")

	in := GeneratedInput{
		Root:         root,
		ChangedFiles: []string{"api/x.pb.go", "root_templ.go", "ui/app.css", "views/home_templ.go", "views/page.templ", "views/page_templ.go", "views/schema.cue"},
		BaseFile:     fileReader(baseFiles),
		HeadFile:     fileReader(headFiles),
		SiblingFiles: map[string][]string{"api": {"api/x.pb.go", "api/x.proto"}},
	}
	findings, missing := GeneratedHandEdits(in)
	if len(missing) != 0 {
		t.Fatalf("missing = %v, want none (declared outputs need no directory listing)", missing)
	}
	got := map[string]string{}
	var keys []string
	for _, f := range findings {
		got[f.Key] = f.Detail
		keys = append(keys, f.Key)
	}
	want := []string{"api/x.pb.go", "root_templ.go", "ui/app.css", "views/home_templ.go"}
	if strings.Join(keys, ",") != strings.Join(want, ",") {
		t.Fatalf("finding keys = %v, want %v (sorted)", keys, want)
	}
	for key, cites := range map[string][]string{
		"ui/app.css":          {".fathom/pack.cue", "ui/input.css", "task ui:css"},
		"views/home_templ.go": {"tmpl-kit@1", "views/home.templ", "templ generate"},
		"root_templ.go":       {"tmpl-kit@1", "root.templ"},
		"api/x.pb.go":         {"api/x.proto"},
	} {
		for _, c := range cites {
			if !strings.Contains(got[key], c) {
				t.Errorf("%s detail %q does not cite %q", key, got[key], c)
			}
		}
	}

	// No root: no declaration is read, and the heuristic alone answers as
	// before (the header-less CSS is never flagged).
	in.Root = ""
	findings, _ = GeneratedHandEdits(in)
	for _, f := range findings {
		if f.Key == "ui/app.css" || f.Key == "root_templ.go" {
			t.Errorf("without a root, %s was flagged: %+v", f.Key, f)
		}
	}
}
