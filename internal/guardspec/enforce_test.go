// TestLayerRuleEnforceRestrictedToDeterministicKinds is the "refuse to
// load an enforced rule that has none, naming it" contract (ADR-038 item
// 1): no_cycles and cross_service_direction have no pre-write check over
// one proposed file, so enforce:true on either is a load error naming the
// rule and its kind.
func TestLayerRuleEnforceRestrictedToDeterministicKinds(t *testing.T) {
	cases := []struct {
		kind string
		body string
	}{
		{"no_cycles", `scope: ["internal/**"]`},
		{"cross_service_direction", `from_service: "a"
		to_service: "b"`},
	}
	for _, tc := range cases {
		t.Run(tc.kind, func(t *testing.T) {
			src := `layer_rules: [{
	id: "x"
	kind: "` + tc.kind + `"
	sentence: "s"
	enforce: true
	` + tc.body + `
}]`
			path := writeGuards(t, src)
			_, err := LoadLayerRules(path)
			if err == nil {
				t.Fatal("expected an error for enforce:true on a non-deterministic kind")
			}
			if !strings.Contains(err.Error(), "enforce") {
				t.Errorf("error = %v, want it to name the enforce field", err)
			}
		})
	}
	// import_direction and boundary are fine with enforce:true.
	for _, tc := range []string{
		`kind: "import_direction"
		from: ["a"]
		to: ["b"]`,
		`kind: "boundary"
		allow: ["a"]
		guarded: ["b"]`,
	} {
		src := `layer_rules: [{
	id: "y"
	sentence: "s"
	enforce: true
	` + tc + `
}]`
		path := writeGuards(t, src)
		set, err := LoadLayerRules(path)
		if err != nil {
			t.Fatalf("%s: unexpected error: %v", tc, err)
		}
		if !set.Rules[0].Enforce {
			t.Errorf("%s: Enforce not decoded true", tc)
		}
	}
}

// TestLoadGuards_EnforceRequiresACheck pins the guard-side half of the
// same "refuse to load, naming it" contract.
func TestLoadGuards_EnforceRequiresACheck(t *testing.T) {
	path := writeGuards(t, `guards: [{scopes: ["**/*.go"], note: "n", enforce: true}]`)
	_, err := LoadGuards(path)
	if err == nil {
		t.Fatal("expected an error for enforce:true with no forbidden_paths/checks/command_scopes")
	}
	if !strings.Contains(err.Error(), "enforce") {
		t.Errorf("error = %v, want it to name the enforce field", err)
	}

	// Each of the three ways to satisfy it is accepted.
	for _, cue := range []string{
		`guards: [{scopes: ["**/*.go"], enforce: true, forbidden_paths: ["a.go"]}]`,
		`guards: [{scopes: ["**/*.go"], enforce: true, checks: ["org_token"]}]`,
		`guards: [{command_scopes: ["cp *"], enforce: true}]`,
	} {
		path := writeGuards(t, cue)
		if _, err := LoadGuards(path); err != nil {
			t.Errorf("%s: unexpected error: %v", cue, err)
		}
	}
}

