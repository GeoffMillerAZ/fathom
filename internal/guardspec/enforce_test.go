// TestLoadGuards_ForbiddenPathsOnlyIsGoverning pins the regression this
// wave found the hard way: a guard naming ONLY forbidden_paths (no scopes,
// no command_scopes) governs something and must load, not be rejected as
// "governing nothing".
func TestLoadGuards_ForbiddenPathsOnlyIsGoverning(t *testing.T) {
	path := writeGuards(t, `guards: [{enforce: true, forbidden_paths: ["cmd/fathom/ui/app.css"], note: "generated"}]`)
	set, err := LoadGuards(path)
	if err != nil {
		t.Fatalf("LoadGuards: %v", err)
	}
	if len(set.Guards) != 1 || len(set.Guards[0].ForbiddenPaths) != 1 {
		t.Fatalf("Guards = %v", set.Guards)
	}
}

