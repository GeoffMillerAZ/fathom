package langbench

import (
	"bytes"
	"fmt"
	"go/format"
	"regexp"
	"sort"
	"strings"
)

// DisclosurePath is the generated unsupported-language table, relative to
// the repository root (LB-F25, design §2.1).
const DisclosurePath = "internal/connector/unsupported_language_gen.go"

// extToken is one extension as a queue name spells it: ".ext" or "*.ext",
// a single dot (a multi-dot suffix such as ".tf.json" is not an extension
// filepath.Ext can see).
var extToken = regexp.MustCompile(`^\*?(\.[A-Za-z0-9+_-]+)$`)

// nameExtensions reads a queue entry's extensions from its name's last
// parenthesis ("Perl (.pl .pm .t by sniff)"): plain are the extensions of
// clauses that claim by extension alone; all adds those of clauses that
// qualify the claim ("by sniff", "by glob", "by basename"), which are
// never disclosed but still make an extension ambiguous.
func nameExtensions(name string) (plain, all []string) {
	open := strings.LastIndex(name, "(")
	end := strings.LastIndex(name, ")")
	if open < 0 || end < open {
		return nil, nil
	}
	for _, clause := range strings.FieldsFunc(name[open+1:end], func(r rune) bool { return r == ',' || r == ';' }) {
		qualified := strings.Contains(clause, " by ")
		for _, tok := range strings.Fields(clause) {
			m := extToken.FindStringSubmatch(tok)
			if m == nil {
				continue
			}
			all = append(all, m[1])
			if !qualified {
				plain = append(plain, m[1])
			}
		}
	}
	return plain, all
}

// DisclosureTable is the unsupported-language table (LB-F25): for every
// queued language (kind "language") with no registration, each extension
// its name claims by extension alone, mapped to its queue id — except an
// extension that more than one queue entry names (in any clause, sniffed
// or not: a wrong guess would be a silent-wrongness class of its own) and
// an extension the connector already classifies (claimed reports it).
func DisclosureTable(q []QueueEntry, registered map[string]Registration, claimed func(ext string) bool) map[string]string {
	owners := map[string]map[string]bool{}
	for _, e := range q {
		_, all := nameExtensions(e.Name)
		for _, x := range all {
			if owners[x] == nil {
				owners[x] = map[string]bool{}
			}
			owners[x][e.ID] = true
		}
	}
	out := map[string]string{}
	for _, e := range q {
		if e.Kind != "language" {
			continue
		}
		if _, ok := registered[e.ID]; ok {
			continue
		}
		plain, _ := nameExtensions(e.Name)
		for _, x := range plain {
			if len(owners[x]) != 1 || (claimed != nil && claimed(x)) {
				continue
			}
			out[x] = e.ID
		}
	}
	return out
}

// RenderDisclosure renders DisclosureTable as the connector's generated Go
// source (DisclosurePath): sorted, gofmt'd, byte-stable.
func RenderDisclosure(q []QueueEntry, registered map[string]Registration, claimed func(ext string) bool) ([]byte, error) {
	table := DisclosureTable(q, registered, claimed)
	exts := make([]string, 0, len(table))
	for x := range table {
		exts = append(exts, x)
	}
	sort.Strings(exts)
	var b bytes.Buffer
	b.WriteString("// Code generated by `indexbench lang-disclosure`; DO NOT EDIT.\n\n")
	b.WriteString("package connector\n\n")
	b.WriteString("// unsupportedLangExtMap is generated from docs/plans/language-breadth.queue.json\n")
	b.WriteString("// (LB-F25, design §2.1): every queued language with no registered extractor\n")
	b.WriteString("// or dialect, by each extension its queue name claims unambiguously — an\n")
	b.WriteString("// extension two queue entries name, or one claimed only by sniff or glob,\n")
	b.WriteString("// is never listed. A language leaves the table when its dialect registers.\n")
	b.WriteString("var unsupportedLangExtMap = map[string]string{\n")
	for _, x := range exts {
		fmt.Fprintf(&b, "\t%q: %q,\n", x, table[x])
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}
