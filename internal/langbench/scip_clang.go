// scip-clang (LB-F80) indexes the preprocessed translation unit, so a
// definition a macro writes is reported at the macro's invocation: libuv's
// `TEST_IMPL(loop_stop) {` is the function `run_test_loop_stop`, its range
// spanning `TEST_IMPL`. No syntactic extractor sees that name; the harness
// leaves such a definition out of L1 as macro-generated (ScoreL1) and
// discloses the count.

var clangIdentRE = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_]*$`)

// clangMacroGenerated reports whether a scip-clang definition named name,
// reported over written (the source text at its range), was generated by a
// macro: what is written is a different identifier than the name.
func clangMacroGenerated(name, written string) bool {
	return written != name && clangIdentRE.MatchString(written)
}

// clangDefName reads one scip-clang definition's name and kind from its
// symbol and the line text it is reported on (columns [c0, c1) of line):
//   - a macro's symbol is its location (`src/inet.c:25:9`!), never its name;
//     the name is what is written at its range;
//   - a nameless record or enum is `$anonymous_type_N`, which nothing writes:
//     kind "anonymous", left out of L1 by the kind intersection and tallied;
//   - a `union` is a type to scip-clang and, with no kind of its own, is
//     read from the keyword written before its name.
func clangDefName(name, kind, sym, line string, c0, c1 int) (string, string) {
	if c0 < 0 || c0 > c1 || c1 > len(line) {
		return name, kind
	}
	written := line[c0:c1]
	switch {
	case strings.HasSuffix(sym, "!") && clangIdentRE.MatchString(written):
		name = written
	case strings.HasPrefix(name, "$anonymous"):
		kind = "anonymous"
	case kind == "type" && strings.HasSuffix(strings.TrimRight(line[:c0], " \t"), "union") && clangIdentRE.MatchString(written):
		kind = "union"
	}
	return name, kind
}

// clangDedupe drops a definition scip-clang repeats: a source file compiled in
// more than one translation unit (a library built static and shared, a header
// every unit includes) is indexed once per unit, and its definitions repeat
// at the same place. defs arrive sorted by path, line and name.
func clangDedupe(defs []OracleDef) []OracleDef {
	out := defs[:0]
	for _, d := range defs {
		if n := len(out); n > 0 && out[n-1] == d {
			continue
		}
		out = append(out, d)
	}
	return out
}

// SCIPDocuments are the relative paths of the documents a SCIP index holds,
// and its producer's name. scip-clang indexes only the translation units a
// compilation database lists, so L1 and L2 score fathom's definitions in these
// files only (LB-F80).
func SCIPDocuments(raw []byte) (docs map[string]bool, tool string, err error) {
	idx := &scippb.Index{}
	if err := proto.Unmarshal(raw, idx); err != nil {
		return nil, "", fmt.Errorf("scip: decode index: %w", err)
	}
	docs = map[string]bool{}
	for _, d := range idx.GetDocuments() {
		docs[d.GetRelativePath()] = true
	}
	return docs, idx.GetMetadata().GetToolInfo().GetName(), nil
}

// clangMacroCall reads the macro written at range r (0-based line, start and
// end columns) when it is invoked as a call: an identifier followed, on its
// line, by `(`.
func clangMacroCall(lines [][]byte, r [4]int32) (string, bool) {
	if r[0] != r[2] || int(r[0]) >= len(lines) || r[1] < 0 || r[1] > r[3] || int(r[3]) > len(lines[r[0]]) {
		return "", false
	}
	name := string(lines[r[0]][r[1]:r[3]])
	if !clangIdentRE.MatchString(name) || !dartCallAt(lines, r, name) {
		return "", false
	}
	return name, true
}

// clangMacroArgCall reports whether a callable reference at range r is a call
// written inside a macro's argument: scip-clang references it at the macro's
// own name (`ASSERT_OK(uv_ip4_addr(...))` references uv_ip4_addr over
// `ASSERT_OK`), so the range is an invocation `NAME(` and the callee is written
// as a call later on that line.
func clangMacroArgCall(lines [][]byte, r [4]int32, callee string) bool {
	if r[0] != r[2] || int(r[0]) >= len(lines) || r[1] < 0 || r[1] > r[3] || int(r[3]) > len(lines[r[0]]) {
		return false
	}
	line := lines[r[0]]
	if !clangIdentRE.MatchString(string(line[r[1]:r[3]])) || !dartCallAt(lines, r, string(line[r[1]:r[3]])) || !clangIdentRE.MatchString(callee) {
		return false
	}
	rest := string(line[r[3]:])
	for from := 0; ; {
		i := strings.Index(rest[from:], callee)
		if i < 0 {
			return false
		}
		i += from
		end := i + len(callee)
		if (i == 0 || !isIdentByte(rest[i-1])) && (end >= len(rest) || !isIdentByte(rest[end])) &&
			strings.HasPrefix(strings.TrimLeft(rest[end:], " \t"), "(") {
			return true
		}
		from = end
	}
}

func isIdentByte(c byte) bool {
	return c == '_' || c >= '0' && c <= '9' || c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z'
}

// CntScipDefsFiles and CntScipDefsAnonymous count the scip-clang definitions
// def_mapping leaves out as no definition a source-level extractor could name
// (ClangDefNames, LB-F292): a file's own symbol (`<file>/src/a.c`/, one per
// document) and a nameless type or namespace (`$anonymous_type_N#`,
// `$anonymous_namespace_<file>`/), which L1 leaves out by its kind too.
const (
	CntScipDefsFiles     = "scip_defs_files"
	CntScipDefsAnonymous = "scip_defs_anonymous"
	// CntScipDefsOutOfScope and CntScipEdgesOutOfScope count the definitions,
	// and the references, in documents the reading does not measure
	// (ClangScope, LB-F292: fmt's bundled gtest, a test the -only globs leave
	// out), counted apart from def_mapping and typed_recall.
	CntScipDefsOutOfScope  = "scip_defs_out_of_scope"
	CntScipEdgesOutOfScope = "scip_edges_out_of_scope"
)

// CntScipFileEdgesNamespace counts the file-edge truth pairs a reference to a scip-clang
// namespace would draw under K25 ruling 3 that nothing else draws (owner ruling L2, O806):
// a scip-clang namespace symbol draws no file edge (clangNamespace).
const CntScipFileEdgesNamespace = "scip_file_edges_namespace"

// clangNamespace reports whether sym is a namespace scip-clang (tool) wrote: a symbol
// whose last descriptor is a namespace (it ends in '/'; `fmt/`, `fmt/detail/`, an
// anonymous namespace), never a document's own `<file>` symbol (`<file>/src/a.cc`/),
// which an #include reaches and which keeps its file edge.
//
// Owner ruling L2 (O806): such a symbol draws no file edge. scip-clang writes a
// Definition at every `namespace fmt {` block, so a namespace a library reopens in each
// of its files is "defined" in every one, and K25 ruling 3 (every defining document) made
// any reference to it an edge to all of them (spdlog: 25,670 pairs where the first
// definer drew 347). In C++ reopening a namespace adds declarations to it and makes no
// file depend on another: what a file depends on is the header declaring the member it
// names, an edge the member's own symbol draws. K18 holds a namespace to file granularity,
// never a symbol of its own, and scip-go's package, defined at every package clause,
// draws no file edge for the same reason (LB-F298). Only the file-edge truth changes:
// def_mapping still maps a scip-clang namespace to the dialect's namespace definition
// (C++ tags namespaces, kind `namespace`) and typed_recall still counts a reference to one.
func clangNamespace(tool, sym string) bool {
	return tool == "scip-clang" && strings.HasSuffix(sym, "/") && !strings.Contains(sym, " `<file>/")
}

// CntScipFileEdgesInternalLinkage counts the file-edge truth pairs K25 ruling 3 would draw
// from a reference to a file-local function or object to another translation unit's
// same-named copy that nothing else draws (owner ruling M3, O863; ClangLinkage).
const CntScipFileEdgesInternalLinkage = "scip_file_edges_internal_linkage"

// ClangLinkage is owner ruling M3 (O863, K19), C's linkage rule for scip-clang's file-edge
// truth: a reference to a file-local function or object resolves to the definition in the
// referring document's own translation unit, never to another unit's same-named copy.
//
// C11 6.2.2p3: a file-scope identifier of an object or a function declared `static` has
// internal linkage, and p2: "each declaration of a particular identifier with internal
// linkage denotes the same object or function" within one translation unit only. libuv's
// 73 test files each define `static void close_cb(uv_handle_t*)`: 73 functions, each
// called only from its own file. scip-clang 0.4.0 names them all `close_cb(74ef0d3a…).`
// (one signature, one symbol), and K25 ruling 3 (a symbol several documents define
// resolves to every one) made each file's reference to its own close_cb an edge to the 72
// others: every test file reached every other (8,613 of libuv's pairs). A translation unit
// is a source file and the headers its #include lines reach (5.1.1.1), so the copy a
// reference means is the one defined in the referring document itself (no cross-file
// edge) or in a header its includes reach. An identifier with external linkage denotes
// one entity across the program (p2), so a function two documents define (two platforms'
// copies, a test double) keeps ruling 3: every definer. This is clangNamespace's shape
// (owner ruling L2): a producer's symbol that names no one file is read by the language's
// own rule, and only the file-edge truth changes (def_mapping and typed_recall do not
// read it).
//
// Which copies have internal linkage is the build's own compiler's AST
// (calibration/oracles/clang-ast-defs `internal_linkage`, tier A), never the written
// text: the compiler gives a definition written without `static` after a `static`
// prototype internal linkage (p4, p5), reads a `static` a macro writes, and splits
// `static int a, b;` into two objects, none of which a token before the name says. Which
// files a document's includes reach is the build's preprocessor oracle's `imports`
// (calibration/oracles/scip-clang/preproc, tier A). Both come from the files the reading
// already passes (Read); with neither, the rule draws as ruling 3 does.
//
// A reference whose includes reach no internal copy draws to the external definers when
// there are any (its unit declares the identifier extern), else to every definer, as
// ruling 3 does: a header naming a static its includers define (each includer's unit has
// its own) is such a reference, and the pairs are counted in the note.
type ClangLinkage struct {
	fileLocal map[string]map[string]bool // document -> identifiers it defines with internal linkage
	includes  map[string][]string        // document -> subject files its #include lines entered
	reach     map[string]map[string]bool // memo: a document's include closure, itself included
	removed   map[[2]string]bool         // pairs ruling 3 would draw to another unit's copy
	unplaced  map[[2]string]bool         // pairs drawn as ruling 3 draws: the includes reach no copy
	read      bool                       // Read ran over at least one oracle file
}

// clangLinkageFor is the dialect's linkage rule: C's (owner ruling M3), none for any other
// this wave (C++'s internal linkage also takes in an unnamed namespace and namespace-scope
// const objects, and needs its own ruling and holdout).
func clangLinkageFor(dialect string) *ClangLinkage {
	if dialect != "c" {
		return nil
	}
	return &ClangLinkage{}
}

// FileLocal records that document path defines the file-scope identifier name with
// internal linkage.
func (l *ClangLinkage) FileLocal(path, name string) {
	if l.fileLocal == nil {
		l.fileLocal = map[string]map[string]bool{}
	}
	if l.fileLocal[path] == nil {
		l.fileLocal[path] = map[string]bool{}
	}
	l.fileLocal[path][name] = true
}

// Include records that an #include line in document from entered subject file to.
func (l *ClangLinkage) Include(from, to string) {
	if l.includes == nil {
		l.includes = map[string][]string{}
	}
	if !slices.Contains(l.includes[from], to) {
		l.includes[from] = append(l.includes[from], to)
	}
	l.reach = nil
}

// Read takes the rule's facts from a reading's tool oracle files: each file's `imports`
// (the preprocessor oracle's) and the `internal_linkage` of its companion (companion(p),
// clang-ast-defs' output beside it). A missing companion is no error: it leaves the
// linkage unknown, as an oracle file without it does. A nil rule reads nothing.
func (l *ClangLinkage) Read(toolOracles []string, companion func(string) string) error {
	if l == nil {
		return nil
	}
	for _, p := range toolOracles {
		b, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		var imp struct {
			Imports []struct {
				Path   string `json:"path"`
				ToPath string `json:"to_path"`
			} `json:"imports"`
		}
		if err := json.Unmarshal(b, &imp); err != nil {
			return fmt.Errorf("%s: %w", p, err)
		}
		for _, i := range imp.Imports {
			if i.Path != "" && i.ToPath != "" {
				l.Include(i.Path, i.ToPath)
			}
		}
		l.read = true
		cb, err := os.ReadFile(companion(p))
		if errors.Is(err, fs.ErrNotExist) {
			continue
		} else if err != nil {
			return err
		}
		var lk struct {
			InternalLinkage []struct {
				Path string `json:"path"`
				Name string `json:"name"`
			} `json:"internal_linkage"`
		}
		if err := json.Unmarshal(cb, &lk); err != nil {
			return fmt.Errorf("%s: %w", companion(p), err)
		}
		for _, d := range lk.InternalLinkage {
			l.FileLocal(d.Path, d.Name)
		}
	}
	return nil
}

// clangFileScope is the identifier of a scip-clang symbol for a file-scope function or
// object (`cxx . . $ close_cb(74ef0d3a3c5968a2).`, `cxx . . $ close_cb_called.`): one term
// or function descriptor and nothing around it. A member, a type, a namespace, a file, a
// macro and a local have no linkage of their own here.
func clangFileScope(sym string) (string, bool) {
	f := strings.SplitN(sym, " ", 5)
	if len(f) != 5 || f[0] != "cxx" {
		return "", false
	}
	d := f[4]
	name, _ := scipBareName(sym)
	if name == "" || !clangIdentRE.MatchString(name) || !strings.HasPrefix(d, name) {
		return "", false
	}
	switch rest := d[len(name):]; {
	case rest == ".":
		return name, true
	case strings.HasPrefix(rest, "(") && strings.HasSuffix(rest, ").") && !strings.ContainsAny(rest[1:len(rest)-2], "()#/.`"):
		return name, true
	}
	return "", false
}

// holds reports whether the rule reads a reference to sym, a scip-clang symbol defined in
// the documents tos: a file-scope function or object at least two documents define, one
// of them with internal linkage.
func (l *ClangLinkage) holds(tool, sym string, tos []string) bool {
	if l == nil || len(l.fileLocal) == 0 || tool != "scip-clang" || len(tos) < 2 {
		return false
	}
	name, ok := clangFileScope(sym)
	if !ok {
		return false
	}
	for _, to := range tos {
		if l.fileLocal[to][name] {
			return true
		}
	}
	return false
}

// reaches reports whether file is doc or a subject file doc's #include lines reach.
func (l *ClangLinkage) reaches(doc, file string) bool {
	if doc == file {
		return true
	}
	if l.reach == nil {
		l.reach = map[string]map[string]bool{}
	}
	r, ok := l.reach[doc]
	if !ok {
		r = map[string]bool{doc: true}
		queue := []string{doc}
		for len(queue) > 0 {
			f := queue[0]
			queue = queue[1:]
			for _, to := range l.includes[f] {
				if !r[to] {
					r[to] = true
					queue = append(queue, to)
				}
			}
		}
		l.reach[doc] = r
	}
	return r[file]
}

// draw draws doc's reference to sym (holds) to the copies it means: the internal copies in
// doc's own translation unit (doc itself draws no edge), else the external definers, else,
// its includes reaching no copy, every definer. It keeps ruling 3's first- and
// later-definer accounting (definerEdges) and records the pairs it does not draw.
func (l *ClangLinkage) draw(d *definerEdges, doc, sym string, tos []string, edges map[[2]string]bool) {
	name, _ := clangFileScope(sym)
	var own, ext []string
	for _, to := range tos {
		switch {
		case !l.fileLocal[to][name]:
			ext = append(ext, to)
		case l.reaches(doc, to):
			own = append(own, to)
		}
	}
	kept, unplaced := own, false
	if kept == nil {
		kept = ext
	}
	if kept == nil {
		kept, unplaced = tos, true
	}
	d.init()
	if l.removed == nil {
		l.removed, l.unplaced = map[[2]string]bool{}, map[[2]string]bool{}
	}
	for i, to := range tos {
		if to == doc {
			continue
		}
		e := [2]string{doc, to}
		if !slices.Contains(kept, to) {
			l.removed[e] = true
			continue
		}
		edges[e] = true
		if unplaced {
			l.unplaced[e] = true
		}
		if i == 0 {
			d.first[e] = true
		} else {
			d.later[e] = true
		}
	}
}

// Finish counts the pairs the rule left out that nothing else drew
// (scip_file_edges_internal_linkage) once ScoreSCIPWith has drawn every edge, and returns
// the subject's disclosure, read beside K25 ruling 3's (EveryDefinerNote). A nil rule, or
// one that read no oracle file and left nothing out, writes nothing.
func (l *ClangLinkage) Finish(name string, edges map[[2]string]bool, counts map[string]int) []string {
	if l == nil {
		return nil
	}
	n := 0
	for e := range l.removed {
		if !edges[e] {
			n++
		}
	}
	if n > 0 {
		counts[CntScipFileEdgesInternalLinkage] += n
	}
	if len(l.fileLocal) == 0 {
		if !l.read {
			return nil
		}
		return []string{fmt.Sprintf("%s: the reading's clang-ast-defs companion carries no internal_linkage, so owner ruling M3 (O863: a reference to a file-local function or object resolves within its own translation unit) read no linkage and K25 ruling 3 draws every definer", name)}
	}
	note := fmt.Sprintf("%s: %d file-edge truth pairs K25 ruling 3 would draw from a reference to a file-local function or object to another translation unit's same-named copy are left out (%s, owner ruling M3, O863: an identifier declared `static` at file scope has internal linkage, C11 6.2.2p3, and denotes its own unit's definition, so the reference resolves to the copy in the referring document or in a header its includes reach, by the build's preprocessor oracle; scip-clang 0.4.0 names every copy alike; linkage is the compiler AST's, clang-ast-defs, tier A; an external-linkage symbol keeps ruling 3)", name, n, CntScipFileEdgesInternalLinkage)
	if u := len(l.unplaced); u > 0 {
		note += fmt.Sprintf("; %d pairs keep ruling 3 because the referring document's includes reach no copy and no definer is external (a header naming a static its includers define)", u)
	}
	return []string{note}
}

// clangMappedName is the name def_mapping looks a scip-clang definition up by
// (ClangDefNames), and the counter it is counted under instead of scip_defs
// when it is no nameable definition (apart, "" otherwise). A macro's symbol is
// its location (`src/inet.c:25:9`!), so its name is what is written at its
// range r (0-based line, start and end columns of lines). A file's own symbol
// stays a definition the file-edge truth reaches through an #include's
// reference; only def_mapping leaves it out.
func clangMappedName(name, sym string, lines [][]byte, r [4]int32) (string, string) {
	if strings.HasSuffix(sym, "`/") && strings.Contains(sym, " `<file>/") {
		return name, CntScipDefsFiles
	}
	if strings.HasPrefix(name, "$anonymous") {
		return name, CntScipDefsAnonymous
	}
	if !strings.HasSuffix(sym, "!") || r[0] != r[2] || int(r[0]) >= len(lines) {
		return name, ""
	}
	line := lines[r[0]]
	if r[1] < 0 || r[1] > r[3] || int(r[3]) > len(line) {
		return name, ""
	}
	if written := string(line[r[1]:r[3]]); clangIdentRE.MatchString(written) {
		return written, ""
	}
	return name, ""
}

// clangGeneratedDef reports whether a scip-clang definition named name (as
// clangMappedName names it) at range r is written by a macro (LB-F293): what
// is written there is another identifier, as SCIPDefs judges it for L1
// (libuv's `TEST_IMPL(timer) {` defines run_test_timer, fmt's
// FMT_BEGIN_NAMESPACE the namespace fmt). A destructor written as its class
// and an operator written `operator` are written as named; a nameless
// definition is never judged.
func clangGeneratedDef(name string, lines [][]byte, r [4]int32) bool {
	if name == "" || strings.HasPrefix(name, "$anonymous") {
		return false
	}
	if r[0] != r[2] || r[0] < 0 || int(r[0]) >= len(lines) {
		return false
	}
	line := lines[r[0]]
	if r[1] < 0 || r[1] > r[3] || int(r[3]) > len(line) {
		return false
	}
	written := string(line[r[1]:r[3]])
	if written == "operator" || written == strings.TrimPrefix(name, "~") {
		return false
	}
	return clangMacroGenerated(name, written)
}

// clangNamedNear reports whether a fathom definition of a name starts within two
// lines of line (spans: def_mapping's fathomAt entry for the name), so a
// macro-written definition the dialect names anyway counts as any other.
func clangNamedNear(spans [][2]int, line int) bool {
	for _, sp := range spans {
		if d := sp[0] - line; d >= -2 && d <= 2 {
			return true
		}
	}
	return false
}

// clangGeneratedBody is the source a macro-generated definition at range r
// owns (scip-clang gives such a definition no enclosing_range): from r's start
// through the brace block that follows the invocation's balanced arguments,
// read past comments, string and character literals; r itself when no block
// follows (a macro that declares, `DEFINE_LIST(item);`) or the block never
// closes.
func clangGeneratedBody(lines [][]byte, r [4]int32) [4]int32 {
	l, c := int(r[0]), int(r[3])
	at := func() byte {
		if l < len(lines) && c < len(lines[l]) {
			return lines[l][c]
		}
		return '\n'
	}
	next := func() bool { // advance one byte; false at the end of the source
		if l >= len(lines) {
			return false
		}
		if c < len(lines[l]) {
			c++
			return true
		}
		l, c = l+1, 0
		return l < len(lines)
	}
	peek := func() byte {
		if l < len(lines) && c+1 < len(lines[l]) {
			return lines[l][c+1]
		}
		return '\n'
	}
	// skip moves past whitespace and comments.
	skip := func() bool {
		for l < len(lines) {
			switch b := at(); {
			case b == ' ' || b == '\t' || b == '\r' || b == '\n':
				if !next() {
					return false
				}
			case b == '/' && peek() == '/':
				l, c = l+1, 0
			case b == '/' && peek() == '*':
				next()
				next()
				for l < len(lines) && (at() != '*' || peek() != '/') {
					if !next() {
						return false
					}
				}
				next()
				next()
			default:
				return true
			}
		}
		return false
	}
	// balanced reads from an opening byte to its matching close, the cursor on
	// the close; strings, characters and comments are skipped.
	balanced := func(open, close byte) bool {
		depth := 0
		for l < len(lines) {
			switch b := at(); {
			case b == '/' && (peek() == '/' || peek() == '*'):
				if !skip() {
					return false
				}
				continue
			case b == '"' || b == '\'':
				for next() && at() != b {
					if at() == '\\' {
						next()
					}
					if at() == '\n' {
						return false
					}
				}
			case b == open:
				depth++
			case b == close:
				depth--
				if depth == 0 {
					return true
				}
			}
			if !next() {
				return false
			}
		}
		return false
	}
	if !skip() || at() != '(' || !balanced('(', ')') {
		return r
	}
	next()
	if !skip() || at() != '{' || !balanced('{', '}') {
		return r
	}
	return [4]int32{r[0], r[1], int32(l), int32(c + 1)}
}

// clangWithoutGenerated is the index with every occurrence inside a
// macro-generated definition's body removed (clangGeneratedBody, the
// definition's own included) when no fathom definition starts on its line
// (gtest's `TEST(suite, name) {` is the dialect's TEST there, and
// internal/scip joins by line), so internal/scip's import counts no edge from
// or to a definition fathom has no symbol for (LB-F293,
// rustWithoutGenerated's shape for a producer that gives the definition no
// enclosing_range): curl's typecheck macros reference the CURLWARNING-written
// Wcurl_* functions at every curl_easy_setopt, and its `BIT(connected);`
// writes a bit-field. It returns the index as bytes and whether any
// definition was generated.
func clangWithoutGenerated(idx *scippb.Index, src func(path string) []byte, nodes []core.SymbolNode) ([]byte, bool, error) {
	at := map[string]map[int]bool{} // file -> lines a fathom definition starts on
	for _, n := range nodes {
		if at[n.FilePath] == nil {
			at[n.FilePath] = map[int]bool{}
		}
		at[n.FilePath][n.Line] = true
	}
	changed := false
	out := &scippb.Index{Metadata: idx.GetMetadata(), ExternalSymbols: idx.GetExternalSymbols()}
	for _, d := range idx.GetDocuments() {
		var lines [][]byte
		var cuts [][4]int32
		for _, o := range d.GetOccurrences() {
			if o.GetSymbolRoles()&int32(scippb.SymbolRole_Definition) == 0 {
				continue
			}
			r, ok := rangeOf(o.GetRange())
			if !ok {
				continue
			}
			if lines == nil {
				lines = bytes.Split(src(d.GetRelativePath()), []byte("\n"))
			}
			name, _ := scipBareName(o.GetSymbol())
			name, apart := clangMappedName(name, o.GetSymbol(), lines, r)
			if apart == "" && clangGeneratedDef(name, lines, r) && !at[d.GetRelativePath()][int(r[0])+1] {
				cuts = append(cuts, clangGeneratedBody(lines, r))
			}
		}
		if len(cuts) == 0 {
			out.Documents = append(out.Documents, d)
			continue
		}
		changed = true
		nd := proto.Clone(d).(*scippb.Document)
		nd.Occurrences = nd.Occurrences[:0]
		for _, o := range d.GetOccurrences() {
			if r, ok := rangeOf(o.GetRange()); ok && inAny(cuts, r) {
				continue
			}
			nd.Occurrences = append(nd.Occurrences, o)
		}
		out.Documents = append(out.Documents, nd)
	}
	if !changed {
		return nil, false, nil
	}
	raw, err := proto.Marshal(out)
	return raw, true, err
}

// clangTyped re-reads typed_recall for scip-clang (ClangDefNames): first over
// the documents the reading measures (ClangScope, LB-F292; a reference out of
// them, or to a definition only they hold, is counted under
// CntScipEdgesOutOfScope), then without the references written inside a
// definition a macro writes (clangWithoutGenerated, LB-F293, counted under
// CntScipEdgesMacroGenerated). counts holds ImportIndex's reading of the whole
// index and is updated in place.
func clangTyped(idx *scippb.Index, service string, nodes []core.SymbolNode, opts SCIPOptions, counts map[string]int) error {
	reread := func(raw []byte, counter string) error {
		imp, err := fscip.ImportIndex(service, raw, nodes)
		if err != nil {
			return err
		}
		kept := imp.Report.Direct + imp.Report.Skipped["unmapped-endpoint"]
		if n := counts[CntScipEdges] - kept; n > 0 {
			counts[counter] += n
			counts[CntScipEdges] = kept
			counts[CntScipEdgesTyped] = imp.Report.Direct
		}
		return nil
	}
	if opts.ClangScope != nil {
		scoped := &scippb.Index{Metadata: idx.GetMetadata(), ExternalSymbols: idx.GetExternalSymbols()}
		for _, d := range idx.GetDocuments() {
			if opts.ClangScope[d.GetRelativePath()] {
				scoped.Documents = append(scoped.Documents, d)
			}
		}
		if len(scoped.Documents) < len(idx.GetDocuments()) {
			raw, err := proto.Marshal(scoped)
			if err != nil {
				return err
			}
			if err := reread(raw, CntScipEdgesOutOfScope); err != nil {
				return err
			}
			idx = scoped
		}
	}
	cut, any, err := clangWithoutGenerated(idx, opts.Source, nodes)
	if err != nil || !any {
		return err
	}
	return reread(cut, CntScipEdgesMacroGenerated)
}

// CntFileEdgesOracleBlind counts the file pairs fathom draws that the index's
// truth lacks and whose every written site has no occurrence of the index
// (FileEdgesOracleBlind, LB-F296): pairs the oracle cannot judge, left out of
// file_edge_precision under LB-F203's cap (merge.go).
const CntFileEdgesOracleBlind = "file_edges_oracle_blind"

// FileEdgesOracleBlind splits fathom's file-resolved edges for the file-edge
// comparison (LB-F296, LB-F203's rule for a file pair): a pair (from file, to
// file) the truth lacks whose every drawing edge is blind is left out and
// returned in blind, sorted. An edge is blind when the name it binds (the
// target definition's last name segment) is written, word-bounded, somewhere
// in the drawing definition's lines and the index writes no occurrence that
// starts at any of those sites: scip-clang references no type in a template's
// argument list or a function template's return type (`std::shared_ptr<logger>
// basic_logger_mt(`), so the oracle cannot judge what fathom read there. A name
// not written in those lines (an alias, a macro) keeps the edge, as does one
// written on a line where a macro is invoked (the index judges what a macro's
// arguments name at the macro); a pair in the truth, or within one file, is
// never blind.
func FileEdgesOracleBlind(raw []byte, truth map[[2]string]bool, edges []core.Edge, nodes []core.SymbolNode, src func(path string) []byte) ([]core.Edge, [][2]string, error) {
	idx := &scippb.Index{}
	if err := proto.Unmarshal(raw, idx); err != nil {
		return nil, nil, fmt.Errorf("scip: decode index: %w", err)
	}
	type span struct{ first, last int }
	fileOf := map[string]string{}
	nameOf := map[string]string{}
	spans := map[string][]span{}
	for _, n := range nodes {
		fileOf[n.Key()] = n.FilePath
		nameOf[n.Key()] = n.Name
		spans[n.Key()] = append(spans[n.Key()], span{n.Line, max(n.Line, n.EndLine)})
	}
	// starts: per document, the (0-based line, column) where an occurrence
	// starts; a macro's occurrence marks its whole line (column -1): scip-clang
	// reports what a macro's expansion references at the macro's own name, so
	// a name written in its arguments is judged there, never blind.
	starts := map[string]map[[2]int]bool{}
	for _, d := range idx.GetDocuments() {
		m := starts[d.GetRelativePath()]
		if m == nil {
			m = map[[2]int]bool{}
			starts[d.GetRelativePath()] = m
		}
		for _, o := range d.GetOccurrences() {
			if r, ok := rangeOf(o.GetRange()); ok {
				m[[2]int{int(r[0]), int(r[1])}] = true
				if strings.HasSuffix(o.GetSymbol(), "!") {
					m[[2]int{int(r[0]), -1}] = true
				}
			}
		}
	}
	lines := map[string][][]byte{}
	linesOf := func(p string) [][]byte {
		if ls, ok := lines[p]; ok {
			return ls
		}
		ls := bytes.Split(src(p), []byte("\n"))
		lines[p] = ls
		return ls
	}
	blindEdge := func(e core.Edge) bool {
		name := nameOf[e.ToSymbol]
		name = name[strings.LastIndexByte(name, '.')+1:]
		if name == "" || !clangIdentRE.MatchString(name) {
			return false
		}
		ls := linesOf(e.FromFile)
		seenAt := starts[e.FromFile]
		sites := 0
		for _, sp := range spans[e.FromSymbol] {
			for l := sp.first; l <= sp.last && l-1 < len(ls); l++ {
				line := ls[l-1]
				for from := 0; ; {
					i := bytes.Index(line[from:], []byte(name))
					if i < 0 {
						break
					}
					i += from
					end := i + len(name)
					from = end
					if (i > 0 && isIdentByte(line[i-1])) || (end < len(line) && isIdentByte(line[end])) {
						continue
					}
					sites++
					if seenAt[[2]int{l - 1, i}] || seenAt[[2]int{l - 1, -1}] {
						return false
					}
				}
			}
		}
		return sites > 0
	}
	type verdict struct{ blind, any bool }
	pairs := map[[2]string]*verdict{}
	for _, e := range edges {
		to, ok := fileOf[e.ToSymbol]
		if !ok || to == e.FromFile {
			continue
		}
		k := [2]string{e.FromFile, to}
		if truth[k] {
			continue
		}
		v := pairs[k]
		if v == nil {
			v = &verdict{blind: true}
			pairs[k] = v
		}
		v.any = true
		if v.blind && !blindEdge(e) {
			v.blind = false
		}
	}
	var blind [][2]string
	for k, v := range pairs {
		if v.any && v.blind {
			blind = append(blind, k)
		}
	}
	sort.Slice(blind, func(i, j int) bool {
		if blind[i][0] != blind[j][0] {
			return blind[i][0] < blind[j][0]
		}
		return blind[i][1] < blind[j][1]
	})
	if len(blind) == 0 {
		return edges, nil, nil
	}
	cut := map[[2]string]bool{}
	for _, k := range blind {
		cut[k] = true
	}
	kept := make([]core.Edge, 0, len(edges))
	for _, e := range edges {
		if to, ok := fileOf[e.ToSymbol]; ok && cut[[2]string{e.FromFile, to}] {
			continue
		}
		kept = append(kept, e)
	}
	return kept, blind, nil
}
