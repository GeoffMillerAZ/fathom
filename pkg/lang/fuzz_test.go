package lang_test

import (
	"bytes"
	"context"
	"encoding/json"
	"slices"
	"strings"
	"testing"

	"github.com/geoffmilleraz/fathom/pkg/lang"
)

// fuzzSmallLimit is the lowered file limit the second Reader runs under, so
// the limit property is exercised by ordinary inputs.
const fuzzSmallLimit = 64

// LL-24 (design section 8, row 5): Extract never panics and holds its
// limits, whatever the path and bytes. The seeds run in the normal test run
// (go test executes every f.Add input once); `go test -fuzz FuzzExtract` grows
// them. The properties are the Result contract: a clean error only for misuse,
// a stated skip reason from the closed set, a skipped file with no facts,
// non-nil sorted slices, JSON that marshals and repeats byte for byte, and the
// lowered file limit honored.
func FuzzExtract(f *testing.F) {
	for _, s := range []struct{ path, src string }{
		{"infra/main.tf", tfSrc},
		{"a/a.go", "package a\n\nfunc F() { G() }\n\nfunc G() {}\n"},
		{"app.py", "def f():\n    g()\n\ndef g():\n    pass\n"},
		{"rules.yml", "groups:\n- name: g\n  rules:\n  - alert: High\n    expr: up == 0\n"},
		{"Dockerfile", "FROM alpine\nRUN echo\n"},
		{"README.md", "# Title\n\nSee [a](a/a.go).\n"},
		{"Makefile", "all: b\nb:\n\techo hi\n"},
		{"s.cue", "package x\n"},
		{"empty.go", ""},
		{"nul.go", "package a\x00\x00\x00"},
		{"bin.dat", "\x7fELF\x02\x01\x01\x00\x00\x00"},
		{"truncated.go", "package a\n\nfunc F(a int, b"},
		{"nested.json", strings.Repeat("[", 4096)},
		{"braces.tf", strings.Repeat("{", 2048)},
		{"badutf8.py", "def f():\n    return '\xff\xfe\xc0'\n"},
		{"long.go", "package a\n// " + strings.Repeat("x", 100000) + "\n"},
		{"gen.py", "# Code generated by tool. DO NOT EDIT.\ndef f():\n    pass\n"},
		{"x.m", "hello\n"},
		{"../../escape.go", "package a\n"},
		{"", "package a\n"},
	} {
		f.Add(s.path, []byte(s.src))
	}

	r, err := lang.New()
	if err != nil {
		f.Fatal(err)
	}
	f.Cleanup(func() { r.Close() })
	small, err := lang.New(lang.WithLimits(lang.Limits{MaxFileBytes: fuzzSmallLimit}))
	if err != nil {
		f.Fatal(err)
	}
	f.Cleanup(func() { small.Close() })
	skips := []string{"", lang.SkipBinary, lang.SkipOversize, lang.SkipGenerated, lang.SkipAmbiguous, lang.SkipUnclassified, lang.SkipNotLinked}

	f.Fuzz(func(t *testing.T, path string, src []byte) {
		file := lang.File{Path: path, Src: src}
		res, err := r.Extract(context.Background(), file)
		if path == "" {
			if err == nil {
				t.Fatal("an empty path must be an error")
			}
			return
		}
		if err != nil {
			t.Fatalf("Extract(%q, %d bytes): %v", path, len(src), err)
		}
		checkResultContract(t, res, skips)
		a, err := json.Marshal(res)
		if err != nil {
			t.Fatalf("the Result does not marshal: %v", err)
		}
		again, err := r.Extract(context.Background(), file)
		if err != nil {
			t.Fatal(err)
		}
		if b, _ := json.Marshal(again); !bytes.Equal(a, b) {
			t.Fatalf("equal inputs gave different JSON for %q", path)
		}

		lowered, err := small.Extract(context.Background(), file)
		if err != nil {
			t.Fatalf("lowered Extract(%q): %v", path, err)
		}
		checkResultContract(t, lowered, skips)
		if len(src) > fuzzSmallLimit && lowered.Skipped != lang.SkipOversize && lowered.Skipped != lang.SkipBinary {
			t.Fatalf("%d bytes over the lowered limit %d was read (skipped %q)", len(src), fuzzSmallLimit, lowered.Skipped)
		}
	})
}

// checkResultContract holds the invariants every Result keeps.
func checkResultContract(t *testing.T, res lang.Result, skips []string) {
	t.Helper()
	if !slices.Contains(skips, res.Skipped) {
		t.Fatalf("skip reason %q is outside the closed set", res.Skipped)
	}
	if res.Symbols == nil || res.References == nil || res.Unresolved == nil || res.Facts == nil || res.Notes == nil {
		t.Fatalf("a nil slice in the Result would marshal as null: %+v", res)
	}
	if res.Skipped != "" && (len(res.Symbols) != 0 || len(res.References) != 0 || len(res.Unresolved) != 0 || len(res.Facts) != 0) {
		t.Fatalf("a skipped file (%s) holds facts: %+v", res.Skipped, res)
	}
	switch res.Level {
	case "L1", "L2", "L3", "L4", lang.LevelNone, lang.LevelUnmeasured:
	default:
		if res.Skipped == "" || res.Level != "" {
			t.Fatalf("level %q is not a level", res.Level)
		}
	}
	prev := 0
	for _, s := range res.Symbols {
		if s.Line < 0 || s.EndLine < 0 {
			t.Fatalf("negative line in %+v", s)
		}
		if s.Line < prev {
			t.Fatalf("symbols are not sorted by line: %d after %d", s.Line, prev)
		}
		prev = s.Line
	}
}
