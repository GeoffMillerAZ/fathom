func TestExtractSkipReasons(t *testing.T) {
	r := newReader(t)
	small := newReader(t, lang.WithLimits(lang.Limits{MaxFileBytes: 16}))
	cases := []struct {
		name, path, src, want string
		rd                    *lang.Reader
	}{
		{"binary", "b.bin", "\x00\x01\x02binary", lang.SkipBinary, r},
		{"oversize", "a.go", "package a\n// " + strings.Repeat("x", 64) + "\n", lang.SkipOversize, small},
		{"binary beats oversize", "b.bin", "\x00" + strings.Repeat("x", 64), lang.SkipBinary, small},
		{"generated", "gen.py", "# Code generated by tool. DO NOT EDIT.\ndef f():\n    pass\n", lang.SkipGenerated, r},
		{"ambiguous", "x.m", "hello\n", lang.SkipAmbiguous, r},
		{"unclassified", "misc.yaml", "x: 1\n", lang.SkipUnclassified, r},
		{"not linked", "s.cue", "package x\n", lang.SkipNotLinked, r},
		{"read", "a.go", "package a\n", "", r},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			res := extract(t, c.rd, c.path, c.src)
			if res.Skipped != c.want {
				t.Fatalf("skipped %q, want %q", res.Skipped, c.want)
			}
			if c.want != "" && len(res.Symbols) != 0 {
				t.Errorf("a skipped file has symbols: %+v", res.Symbols)
			}
		})
	}
}

func TestSkipReasonsAreTheClosedSet(t *testing.T) {
	closed := map[string]bool{"": true, lang.SkipBinary: true, lang.SkipOversize: true, lang.SkipGenerated: true,
		lang.SkipAmbiguous: true, lang.SkipUnclassified: true, lang.SkipNotLinked: true, lang.SkipBusy: true}
	r := newReader(t)
	for _, p := range []string{"x.m", "x.h", "noext", "x.unknownext", "a.go", "x.cue", "docker-compose.yml"} {
		if got := extract(t, r, p, "x\n").Skipped; !closed[got] {
			t.Errorf("%s: skip reason %q is outside the closed set", p, got)
		}
	}
}

func TestSiblingsDisclosure(t *testing.T) {
	r := newReader(t)
	if n := extract(t, r, "misc.yaml", "x: 1\n").Notes; len(n) != 1 || !strings.HasPrefix(n[0], "siblings-empty") {
		t.Errorf("a YAML file no signal settles, read without siblings, says so: %v", n)
	}
	if n := extract(t, r, "misc.yaml", "x: 1\n", "other.txt").Notes; len(n) != 0 {
		t.Errorf("siblings were given: %v", n)
	}
	if n := extract(t, r, "a.go", "package a\n").Notes; len(n) != 0 {
		t.Errorf("a Go file does not read siblings: %v", n)
	}
	// A sibling list changes the verdict for a role's task file.
	role := "- name: t\n  debug:\n    msg: hi\n"
	with := extract(t, r, "x/tasks/main.yml", role, "x/tasks/main.yml", "x/meta/main.yml")
	if with.Dialect != "ansible" {
		t.Errorf("dialect %q", with.Dialect)
	}
}

func TestExtractMisuse(t *testing.T) {
	r := newReader(t)
	if _, err := r.Extract(context.Background(), lang.File{}); err == nil {
		t.Error("an empty path is an error")
	}
	ctx, cancel := context.WithCancel(context.Background())
	cancel()
	if _, err := r.Extract(ctx, lang.File{Path: "a.go"}); err == nil {
		t.Error("a done context is an error")
	}
	if _, err := r.Extract(context.Background(), lang.File{Path: "a.go", Siblings: make([]string, 1<<20+1)}); err == nil {
		t.Error("an oversized sibling list is an error")
	}
	r.Close()
	r.Close() // idempotent
	if _, err := r.Extract(context.Background(), lang.File{Path: "a.go"}); err != lang.ErrClosed {
		t.Errorf("after Close: %v", err)
	}
}

